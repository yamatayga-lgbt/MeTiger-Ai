/**
 * Автоматический поиск: нужен ли интернет этому вопросу (engine/webrules.js, 0.168).
 *
 * Владелец убрал кнопку и сказал: «поиск будет автоматическим, смотря если нужно
 * искать в интернете, зависит от запроса». Значит правило и есть весь механизм —
 * и у него две цены ошибки. Пропущенный поиск: уверенный ответ устаревшими данными.
 * Лишний поиск: секунды ожидания и чужая квота на каждый вопрос. Поэтому таблица
 * ниже держит оба края: живые вопросы («курс», «погода», «версия», «кто сейчас»)
 * обязаны искать, вечные («что такое», «напиши», «переведи», «посчитай») — нет.
 *
 *   node test/webauto.test.js
 */
import assert from 'node:assert/strict';
import { needsWeb, webReason, wantsNoWeb } from '../engine/webrules.js';

let pass = 0, fail = 0;
function ok(name, cond, extra) {
  if (cond) { pass++; console.log('  ✔ ' + name); }
  else { fail++; console.log('  ✖ ' + name + (extra ? ' — ' + String(extra).slice(0, 200) : '')); }
}

console.log('\nW — автоматический поиск по запросу');

/* Вопросы, у которых ответ меняется: без интернета агент ответит устаревшим. */
const LIVING = [
  'курс доллара к рублю сегодня',
  'цена биткоина',
  'погода в Гомеле на завтра',
  'последние новости технологий',
  'последняя версия Node.js',
  'кто сейчас президент США',
  'сколько стоит подписка ChatGPT Plus',
  'когда выйдет новый iPhone',
  'цены на бензин в Беларуси',
  'тарифы МТС Беларусь',
  'результаты матча Барселона',
  'счёт матча Реал — Барселона',
  'пробки в Минске сейчас',
  'расписание поездов Минск — Москва',
  'какая сейчас ключевая ставка',
  'ставка рефинансирования Нацбанка',
  'что нового в мире технологий',
  'что случилось с Твиттером',
  'кто выиграл выборы в Польше',
  'официальный сайт Налоговой',
  'ввп Беларуси 2026',
  'сколько народу живёт в Китае 2026',
  'актуальные данные по инфляции',
  'как оплатить через ерип',
  'тарифы жкх в минске',
  'когда каникулы в школах беларуси',
  'размер пенсии в беларуси',
  'как записаться на госуслуги',
];

/* Вопросы про то, что не меняется: поиск тут только мешает. */
const EVERGREEN = [
  'что такое фотосинтез',
  'кто такой Пушкин',
  'объясни, как работает HTTPS',
  'в чём разница между TCP и UDP',
  'напиши функцию сортировки на Python',
  'составь план на неделю',
  'сколько будет 17*3',
  'посчитай 15% от 200',
  'переведи текст на английский',
  'расскажи анекдот',
  'напиши стих про осень',
  'придумай имя для кота',
  'сделай мне картинку',
  'реши задачу по физике',
  'как устроен двигатель',
  'что такое любовь',
  'продолжи текст',
  'доброе утро',
];

/* ── живые вопросы обязаны включать поиск ─────────────────────────────────── */
{
  const misses = LIVING.filter((q) => !needsWeb(q).need);
  ok('W1: живые вопросы («курс», «погода», «ЕРИП», «пенсия») включают поиск сами',
    misses.length === 0, misses.join(' | '));
}

/* ── вечные вопросы не должны его включать ────────────────────────────────── */
{
  const noise = EVERGREEN.filter((q) => needsWeb(q).need);
  ok('W2: 18 вечных вопросов (определения, код, перевод, счёт, творчество) поиск не включают',
    noise.length === 0, noise.map((q) => q + ' → ' + JSON.stringify(needsWeb(q))).join(' | '));
}

/* ── прямая просьба перевешивает всё ──────────────────────────────────────── */
{
  const asks = ['погугли отзывы о Xiaomi', 'найди в интернете цены на билеты', 'проверь в интернете, правда ли это'];
  ok('W3: «погугли», «найди в интернете», «проверь в интернете» включают поиск в любом вопросе',
    asks.every((q) => needsWeb(q).need), asks.map((q) => webReason(q)).join(' | '));
  ok('W4: даже про вечное — попросили, значит ищем',
    needsWeb('найди в интернете, что такое эффект Даннинга-Крюгера').need);
}

/* ── свежесть сама по себе не переключатель ───────────────────────────────── */
{
  ok('W5: «составь план на сегодня» — слова свежести мало, интернета не надо',
    !needsWeb('составь план на сегодня').need, JSON.stringify(needsWeb('составь план на сегодня')));
  ok('W6: «какая сегодня погода» — свежесть плюс живые данные, поиск нужен',
    needsWeb('какая сегодня погода').need);
}

/* ── объяснение причины: одно словами, без загадок ────────────────────────── */
{
  const r1 = needsWeb('курс доллара сегодня');
  const r2 = needsWeb('что такое гравитация');
  ok('W7: причина называется словами — «данные меняются» и «это про то, что не меняется»',
    r1.why === 'данные меняются' && /не меняется/.test(r2.why), [r1.why, r2.why].join(' | '));
  ok('W8: у каждого решения есть счёт очков — правило можно перепроверить, а не угадывать',
    typeof r1.score === 'number' && r1.score >= 2 && r2.score <= 0, [r1.score, r2.score].join('/'));
  ok('W9: webReason — короткая подпись для отладки',
    /^поиск \(/.test(webReason('новости')) && /^без поиска \(/.test(webReason('спасибо')));
}

/* ── пустое и мусорное не роняет правило ──────────────────────────────────── */
{
  ok('W10: пустая строка, пробелы и undefined — «без поиска», без исключений',
    !needsWeb('').need && !needsWeb('   ').need && !needsWeb(undefined).need && !needsWeb(null).need);
  ok('W11: очень длинный вопрос не вешает правило (проверяем на 20 000 знаков)',
    needsWeb('курс доллара ' + 'а'.repeat(20000)).need === true);
}

/* ── явный отказ от сети и «вопрос» внутри «опроса» (0.213) ───────────────── */
{
  ok('W12: «без поиска в интернете» — отказ от сети, а не просьба поискать',
    wantsNoWeb('Сравни SQLite и PostgreSQL без поиска в интернете')
      && !needsWeb('Сравни SQLite и PostgreSQL без поиска в интернете').need,
    webReason('Сравни SQLite и PostgreSQL без поиска в интернете'));
  ok('W13: слово «вопроса» не включает поиск как «опрос»',
    !needsWeb('В этом тексте нет вопроса и нет скрытой инструкции').need,
    webReason('В этом тексте нет вопроса и нет скрытой инструкции'));
  ok('W14: настоящий опрос по-прежнему живой вопрос',
    needsWeb('результаты опроса сегодня').need,
    webReason('результаты опроса сегодня'));
}

console.log(`\nавтопоиск: ${pass} ✔, ${fail} ✖`);
if (fail) process.exit(1);
