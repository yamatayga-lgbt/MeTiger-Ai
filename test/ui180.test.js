/**
 * 0.180 «Свежесть»: живой вопрос отвечает умная полоса, а обрыв связи чинится
 * молчаливым повтором.
 *
 * Обе беды нашёл живой стенд 20 вопросов (12 окт 2026, `/home/user/свежесть-20-вопросов.md`):
 *   · ответы на «курс доллара сегодня» и «сколько стоит бензин» писала крошечная
 *     модель (liquid/lfm-2.5-2.6b) — половина выходила мусором вида «в предоставленных
 *     данных нет…» по кривой выдаче, хотя источники под ответом были;
 *   · четыре вопроса из двадцати закончились надписью «связь оборвалась на середине
 *     ответа» при пустом экране — повтор в приложении ловил только ИСКЛЮЧЕНИЯ, а
 *     обрыв приходит обычным ответом с полем error.
 *
 * Здесь держим ровно эти два обещания и место, где они ломаются молча:
 *   · полоса поднимается у живой темы (решает та же функция, что включает поиск);
 *   · чужой выбор не подменяем: выбрал модель или полосу — отвечает она;
 *   · повтор — только когда ничего не показано и человек не останавливал запрос.
 */
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'

const ok = (name, condition, extra) => {
  assert.ok(condition, name + (extra ? ' — ' + JSON.stringify(extra) : ''))
  console.log('  ✔ ' + name)
}

const read = (p) => readFileSync(p, 'utf8')
const door = read('functions/api/chat.js')
const app = read('src/App.tsx')
const search = read('engine/search.js')
const chain = read('package.json')

ok('U180a живой вопрос идёт по умной полосе — решает та же функция, что включает поиск',
  /import \{ needsWeb \} from '\.\.\/\.\.\/engine\/webrules\.js'/.test(door)
    && /needsWeb\(String\(askText \|\| ''\)\s*,\s*\{[^}]*doc:/.test(door)
    && /'smart'/.test(door))

ok('U180b чужой выбор уважаем: выбрана модель — полосу не поднимаем',
  /!norm\.model && \(\(composed && composed\.voice && composed\.voice\.mode === 'note'\)[\s\S]{0,400}needsWeb/.test(door))

ok('U180c обрыв связи повторяется молча — но только если человек ничего не читал',
  /const TRANSPORT_BREAK = \/время вышло\|связь оборвалась\|оборвался\|сеть недоступна\//.test(app)
    && /const worthRetry = \(r: ChatResult\): boolean => !r\.ok && !r\.stopped && !r\.partial/.test(app)
    && /if \(worthRetry\(r\) && attempt < maxRetries - 1\)/.test(app))

ok('U180d смысловые отказы не повторяем — «сервер ответил 503» и лимиты не сеть',
  /время вышло\|связь оборвалась\|оборвался\|сеть недоступна/.test(app)
    && !/сервер ответил/.test(app.split('TRANSPORT_BREAK')[1] || ''))

ok('U180e поиск просит свежее и официальное и требует назвать дату данных',
  /Отдавай предпочтение свежим и официальным источникам/.test(search)
    && /обязательно указывай, на какую дату/.test(search))

ok('U180f проверка подключена к общему прогону',
  /test\/ui180\.test\.js/.test(chain))

console.log('\n✔ 0.180 (свежесть): умная полоса для живых вопросов, повтор при обрыве — проверки пройдены')
