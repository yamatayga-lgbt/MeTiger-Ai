/**
 * Замок страничных жестов (0.160).
 *
 * История. В 0.145 вернулся жест «потянул вниз — страница обновилась»: слушатели
 * стоят на всём документе. В 0.159 у панели «Параметры» появилась ручка, за которую
 * шторку тянут вниз, — и владелец сразу поймал неприятность: «когда я сворачиваю
 * окно параметров, то и страница вместе обновляется, я её задеваю». Так и было:
 * палец тянул шторку, а жест обновления видел то же движение и в конце перезагружал
 * страницу.
 *
 * Решение — два правила, и оба живут здесь, чтобы не расползались по компонентам:
 *
 *   1. `PAGE_GESTURE_OVERLAYS` — селектор всплывающих слоёв. Если касание началось
 *      ВНУТРИ такого слоя (шторка параметров, тень под ней, меню «+», палитра
 *      команд, ящик Workspace), обновление смахиванием не вооружается вообще:
 *      этот жест принадлежит слою, а не странице.
 *
 *   2. `lockPageGesture()` / `unlockPageGesture()` — явный счётчик для тех мест,
 *      где слоя может и не быть под пальцем, но жест страницы всё равно мешает.
 *      Замок считает вложенные блокировки, поэтому «разлочил один раньше другого»
 *      ничего не ломает.
 */

/** Слои, внутри которых смахивание вниз не обновляет страницу. */
export const PAGE_GESTURE_OVERLAYS = [
  '.params-popover',
  '.model-panel',
  '.model-backdrop',
  '.attach-menu',
  '.chat-menu',
  '.palette',
  '.workspace-drawer',
  '.news-modal',
  '.menu-catcher',
].join(', ')

/** Началось ли касание внутри всплывающего слоя. */
export function touchedOverlay(target: EventTarget | null): boolean {
  if (!(target instanceof Element)) return false
  return target.closest(PAGE_GESTURE_OVERLAYS) !== null
}

let locks = 0

/** Запретить страничные жесты (пока счётчик больше нуля). */
export function lockPageGesture(): void {
  locks += 1
}

/** Разрешить обратно (парная к lockPageGesture). */
export function unlockPageGesture(): void {
  locks = Math.max(0, locks - 1)
}

/** Заблокированы ли страничные жесты прямо сейчас. */
export function pageGestureLocked(): boolean {
  return locks > 0
}
