/** Версия, которая сейчас открыта как «главная» запись — свежайшая в списке. */
export const LATEST_NOTE = RELEASE_NOTES[0]?.version || ''

/**
 * Запись для конкретной версии. Её и показывает и окошко, и раздел «Что нового»:
 * версия без записи — не ошибка (сборка ушла раньше текста), а честное «изменений
 * для человека тут нет» — так и говорит экран, вместо выдуманной строки.
 */
export function noteFor(version: string): ReleaseNote | null {
  return RELEASE_NOTES.find((n) => n.version === version) || null
}
