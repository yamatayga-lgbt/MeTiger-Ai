/**
 * «Что нового» — что изменилось в ТЕКУЩЕЙ версии, словами для человека.
 *
 * Показывается ровно одна запись — та, что совпадает с версией продукта
 * (noteFor(APP_VERSION)): после обновления важно «что поменялось у меня сейчас»,
 * а не история продукта (история живёт в README). Прошлые записи лежат здесь
 * архивом и в интерфейс не выводятся.
 *
 * Зачем отдельный файл, а не чтение README: README лежит в репозитории и в
 * собранную оболочку не попадает, а окошко должно открываться без сети — это
 * часть интерфейса, а не документация.
 *
 * Правило пополнения: одна запись на версию, «что изменилось для человека» —
 * первой строкой, детали ниже. Номер в шапке сверяется с src/lib/version.ts
 * тестом (test/front.test.js, блок N): забытая запись — красный тест.
 */
