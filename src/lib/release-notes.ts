/**
 * «Что нового» — запись ТЕКУЩЕЙ версии, словами для человека.
 *
 * Правило владельца (0.189): здесь хранится только ПОСЛЕДНЯЯ запись — та, что
 * совпадает с версией продукта (APP_VERSION). Полная история версий живёт в
 * README, дублировать её в коде незачем. Тексты пишем проще: без названий
 * файлов и внутренних терминов — то, что человек увидел и почувствовал.
 *
 * Номер в записи сверяется с версией продукта автоматическими проверками
 * фронтенда: забытая или лишняя запись — красный тест.
 */
export interface ReleaseNote {
  version: string
  /** Короткий заголовок — то, ради чего версия существует. */
  title: string
  /** Пункты: что человек увидел или почувствовал. */
  items: string[]
  /** Юбилейные и особые вехи — рисуются лентой, а не точкой. */
  mark?: 'jubilee' | 'fix'
}

export const RELEASE_NOTES: ReleaseNote[] = [
  {
    version: '0.194',
    title: 'Безлимитный контекст — всегда, без переключателя',
    items: [
      'Разговоры больше не забывают начало — без всяких настроек: старые реплики сжимаются в выжимку, а не удаляются. Переключатель из «Параметров» убран за ненадобностью.',
      'В выжимку попадает и самая первая реплика целиком — там лежит сама задача; примечание под ответом честно говорит, сколько реплик вошло целиком, а сколько сжато.',
      'Чаты по-прежнему изолированы: удаление чата стирает его историю, медиа и серверную память этого разговора.',
    ],
  },
]

/** Версия, которая сейчас открыта как «главная» запись — свежайшая в списке. */
export const LATEST_NOTE = RELEASE_NOTES[0]?.version || ''

/**
 * Запись для конкретной версии. Её и показывает и окошко, и раздел «Что нового»:
 * версия без записи — не ошибка (сборка ушла раньше текста), а честное «изменений
 * для человека тут нет» — так и говорит экран, вместо выдуманной строки.
 */
export function noteFor(version: string): ReleaseNote | null {
  return RELEASE_NOTES.find((n) => n.version === version) || null
}
