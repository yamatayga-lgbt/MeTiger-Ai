/**
 * Признаки устройства, которые меняют поведение интерфейса, а не просто вид.
 */

/**
 * Enter в поле ввода отправляет сообщение — отдельно от переноса строки (Shift+Enter) —
 * только там, где рядом настоящая клавиатура и мышь/трекпад (hover+точный указатель).
 *
 * Зачем: у телефона и планшета та же клавиша `Enter` у виртуальной клавиатуры подписана
 * «перейти на новую строку» и шлёт то же событие `keydown` с `key === 'Enter'`, а Shift
 * на ней обычно взять неоткуда вовсе. Раньше Enter слал сообщение на любом устройстве —
 * человек писал многострочный текст и с каждой новой строкой случайно отправлял ещё не
 * дописанное. На компьютере это разделение (Enter — отправить, Shift+Enter — перенос)
 * — привычный стандарт чатов, его не трогаем.
 */
export function enterKeySends(): boolean {
  if (typeof window === 'undefined' || typeof window.matchMedia !== 'function') return true
  try {
    return window.matchMedia('(hover: hover) and (pointer: fine)').matches
  } catch {
    /* совсем древний браузер без поддержки этого media-запроса — ведём себя как раньше */
    return true
  }
}
