const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

/* Глобальный шлюз: старт запроса не чаще PACE_MS, независимо от числа слотов.
   Три слота нужны только чтобы медленные ответы не держали очередь. */
let nextSlot = Date.now();
function gate() {
  const now = Date.now();
  const wait = Math.max(0, nextSlot - now);
  nextSlot = Math.max(nextSlot, now) + PACE_MS;
  return sleep(wait);
}

async function ask(p, n) {
  await gate();
  const t0 = Date.now();
  const body = { text: p.q, chatId: 'probe100-' + n, history: [] };
  if (p.persona) body.persona = p.persona;
  const ctl = new AbortController();
  const timer = setTimeout(() => ctl.abort(), TIMEOUT_MS);
  try {
    const r = await fetch(PROD, {
      method: 'POST',
      headers: { 'content-type': 'application/json' },
      body: JSON.stringify(body),
      signal: ctl.signal,
    });
    clearTimeout(timer);
    const ms = Date.now() - t0;
    let d = null;
    try { d = await r.json(); } catch { /* пустое тело */ }
    const reply = String((d && d.reply) || '');
    const row = {
      n, cat: p.cat || 'edge', q: String(p.q).slice(0, 80),
      status: r.status, ms, ok: !!d?.ok,
      replyLen: reply.length,
      replyHead: reply.replace(/\s+/g, ' ').slice(0, 140),
      src: d?.src || '', who: d?.who || '', model: d?.model || '',
      note: p.note || '', expected: p.re ? p.re.test(reply) : null,
      emojiWant: !!p.emoji, structWant: !!p.struct, shortWant: !!p.short, refuse: !!p.refuse,
      empty400: !!p.empty && r.status === 400,
      error: d?.error || '',
    };
    appendFileSync(OUT, JSON.stringify(row) + '\n');
    console.log(`#${n} [${row.cat}] ${row.ok ? 'ok' : 'FAIL'} ${ms}ms ${row.expected === false ? ' ⚠ПРОВЕРКА' : ''} ${row.replyHead}`.slice(0, 150));
  } catch (e) {
    clearTimeout(timer);
    const row = { n, cat: p.cat || 'edge', q: String(p.q).slice(0, 80), status: 0, ms: Date.now() - t0, ok: false, error: String(e?.message || e).slice(0, 80) };
    appendFileSync(OUT, JSON.stringify(row) + '\n');
    console.log(`#${n} [${row.cat}] THROW ${row.error}`);
  }
}

