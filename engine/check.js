/**
 * ✅ Самопроверка ответа — агент сверяет то, что написал, с тем, о чём просили (0.124).
 *
 * Зачем. Совет голов (engine/ensemble.js) проверяет ЧИСЛО: сходятся ли независимые
 * головы на задаче с одним верным ответом. Но большая часть ответов не про число, а
 * про полноту: человек спросил три вещи — ответили на одну; инструмент принёс курс
 * 3,42 — в ответе «около трёх»; попросили план из пяти шагов — прислали два. Ни один
 * из прежних слоёв этого не видит: совет не созывается на болтовне, а роутеру всё
 * равно, сколько пунктов в ответе.
 *
 * Чем проверяется. Двумя проходами, дешёвым и дорогим:
 *   1. СВОИМИ СИЛАМИ (бесплатно, микросекунды): разбор вопроса на подвопросы и
 *      сравнение с ответом — данные инструментов, перечисления, обещанные блоки,
 *      «нет ответа» вместо ответа, обрезанный хвост.
 *   2. ОДНИМ ПРОХОДОМ МОДЕЛИ (платно квотой, поэтому по бюджету и только когда
 *      первый проход нашёл зацепку): той же голове показывают вопрос, её ответ и
 *      найденные зацепки и просят дописать недостающее. Это НЕ вторая голова и не
 *      голосование — чинит тот, кто отвечал, поэтому голос агента не подменяется.
 *
 * Почему первый проход не зовёт модель сразу. Бесплатный пул живёт на квотах
 * (5 запросов в минуту у части роутеров): платить вызовом за каждый «привет» —
 * значит отвечать медленнее и упереться в лимит на ровном месте. Поэтому модель
 * зовётся только там, где уже найдена конкретная зацепка, и не чаще бюджета.
 *
 * Чего слой НЕ делает: не переписывает ответ целиком, не спорит с советом голов
 * (тот отработал раньше), не проверяет стиль. Правит только недостающее и всегда
 * говорит словами, что именно нашёл, — молчание выглядит как «всё хорошо».
 */

/** Сколько подвопросов в вопросе считать перечислением, а не одной мыслью. */
export const MIN_QUESTIONS = 2;

/** Доля чисел из данных инструментов, которая обязана дойти до ответа. */
export const MIN_NUMBER_SHARE = 0.5;

/** Вопрос, ответ на который — число: тогда числа из поиска обязаны дойти до ответа. */
export const ASKS_NUMBER = /(?<![а-яё])(сколько|скольк|курс(?:а|е|у|ы|ом|ов)?(?![а-яё])|цен[аы](?![а-яё])|стоим|процент|температур|населени|площад|рост(?![а-яё])|вес(?![а-яё]|ит|ят)|возраст|когда|в как(?:ом|ой) году|дат[аы](?![а-яё]))|how many|how much|\d/i;

/** Потолок знаков у «ответа», который на деле отказ или отписка. */
export const TOO_SHORT = 40;

/** Конфиг из окружения (в Worker нет process.env — env приходит параметром). */
export function cfgOf(env) {
  const e = env || {};
  const mode = String(e.CHECK || '').toLowerCase();
  const budget = Number(e.CHECK_BUDGET);
  return {
    /* CHECK=off — слой молчит целиком: поведение прежнее, ни одной зацепки. */
    on: mode !== 'off' && e.CHECK !== '0',
    /* Дорогой проход (одна голова на починку). CHECK=free — только бесплатный разбор. */
    fix: mode !== 'free' && e.CHECK_FIX !== '0',
    /* Сколько платных проходов разрешено на один ответ. */
    budget: Number.isFinite(budget) && budget >= 0 ? Math.min(3, budget) : 1,
    minQuestions: Math.max(2, Number(e.CHECK_MIN_QUESTIONS) || MIN_QUESTIONS),
    numberShare: Math.min(1, Math.max(0.1, Number(e.CHECK_NUMBER_SHARE) || MIN_NUMBER_SHARE)),
    tooShort: Math.max(10, Number(e.CHECK_TOO_SHORT) || TOO_SHORT),
  };
}

/* ─────────────────────────── разбор вопроса ─────────────────────────── */

/**
 * Подвопросы: предложения вопроса, которые сами по себе вопрос, плюс пункты списка.
 * «Сделай X, Y и Z» одним предложением тоже даёт несколько тем — их режет запятая
 * с однородными членами, но только когда их действительно несколько.
 */
const ASK_VERB = /^\s*(?:\d{1,2}[.)]\s*)?(посчитай|сравни|объясни|опиши|перечисли|проверь|покажи|напиши|сделай|найди|укажи|распиши|предложи|выбери|расскажи|приведи|дай|подбери|составь|переведи|исправь|оцени|назови|придумай|реши|докажи)/i;
export function askedPoints(text) {
  const raw = String(text || '');
  const out = [];
  const push = (v) => { const one = String(v || '').trim(); if (one.length >= 2 && out.indexOf(one) < 0) out.push(one); };
  /* Маркер пункта: номер или тире, ОБЯЗАТЕЛЬНО с пробелом после. Без пробела «3.42»
     и «п.2» остались бы числами, а не пунктами. */
  const MARKER = /(?:^|[\s.])(?:\d{1,2}[.)]|[-*•])\s+/gu;

  /* Точка внутри числа и внутри сокращения — не конец предложения: «3.42 рубля» и
     «и т. д.» иначе резали вопрос пополам, и половина терялась (короче порога). */
  const t = raw
    .replace(/(\d)\.(?=\d)/g, '$1\u0001')
    /* Арифметика внутри вопроса — не конец предложения: «Сколько будет 2+2?» иначе
       терял первое предложение целиком (оно короче порога длины). */
    .replace(/(\d)\s*([+*/=:])\s*(?=\d)/g, '$1\u0002$2')
    .replace(/\b(т|и т|п|др|см|г|сс|ст)\.\s?(д|п|р|г)?\./gu, (m0) => m0.replace(/\./g, '\u0001'));

  /* 1) предложения вопроса. Граница — знак конца предложения, ПОСЛЕ которого пробел
     или конец строки. Lookbehind не dipakai: `(?<=…)` в движке больше нигде не
     использован, а падение разбора регулярки стоило бы всего ответа. */
  const hasQuestion = /\?/.test(raw);
  const restore = (x) => String(x || '').replace(/\u0001/g, '.').replace(/\u0002/g, '');
  for (const m of t.matchAll(/[^?!\n.]+(?:\.(?=\s|$)|[?!])?/gu)) {
    let one = restore(m[0]).trim();
    if (!one) continue;
    /* Пункты, написанные в одну строку, при резке по предложениям слипаются —
       маркеры не повод выбросить кусок, а повод снять их и разобрать остаток. */
    const parts = one.split(MARKER).map((x) => x.trim()).filter(Boolean);
    for (const part of (parts.length ? parts : [one])) {
      if (part.length < 2) continue;
      /* Знак вопроса сохраняем: по нему обрывок («2») отличается от вопроса
         («Сколько будет 2+2?»), а снимется он уже в norm(). */
      if (/[?]$/.test(part)) push(part.replace(/\s+\?$/, '?').replace(/\.{2,}$/, '.'));
      /* Не только вопросы: «Посчитай бюджет. Сравни с годом.» — перечисление без
         единого «?», и потерять его значит не проверить ответ на полноту.
         Но если в тексте ЕСТЬ вопрос, повествовательное предложение — это условие
         («У Пети 5 яблок, он отдал 2 и купил 7. Сколько стало?»), а не второй
         подвопрос; темой оно остаётся, только если начинается с просьбы-глагола. */
      else if (part.length >= 12 && (!hasQuestion || ASK_VERB.test(part))) push(part.replace(/[.!?]+$/, ''));
    }
  }

  /* 2) пункты списка: «1.», «1)», «- », «* » — человек сам разбил задачу.
     Маркер ищем везде, а не только в начале строки: список в одну строку иначе
     остался бы одним длинным «подвопросом». */
  const items = t.match(/(?:^|[\n.])\s*(?:\d{1,2}[.)]|[-*•])\s+([^\n]{2,}?)(?=\s*(?:\d{1,2}[.)]|[-*•])\s+|$|[\n])/g) || [];
  for (const it of items) {
    push(restore(it.replace(/^[\s.\n]*/, '').replace(/^(?:\d{1,2}[.)]|[-*•])\s+/, '')).trim());
  }

  /* 3) перечисление однородных одним предложением («посчитай, сравни и объясни»).
     Только запасной путь: если предложения уже дали темы, голые глаголы превратили
     бы одну мысль в три «подвопроса», и ответ всегда оказывался бы неполным. */
  if (!out.length) {
    const VERBS = ['посчитай', 'сравни', 'объясни', 'опиши', 'перечисли', 'проверь', 'покажи', 'напиши', 'сделай', 'найди', 'укажи', 'распиши', 'предложи'];
    const low = raw.toLowerCase();
    const found = VERBS.filter((v) => low.indexOf(v) >= 0);
    if (found.length >= 2) for (const v of found) push(v);
  }

  /* Мусор на входе не должен превращаться в темы: «аааа?» — не подвопрос. */
  const clean = out.filter((p) => keywords(p).length > 0 || /[?]$/.test(p));
  /* Одна и та же тема не должна считаться дважды. Впитываем только когда текст
     одной темы ЦЕЛИКОМ лежит внутри другой («Посчитай бюджет» внутри строки
     «Посчитай бюджет. 2. Сравни…»): впитывание по одному общему слову съедало
     соседние пункты перечисления, и ответ вечно оказывался «полным». */
  const norm = (x) => String(x || '').toLowerCase().replace(MARKER, ' ').replace(/\s+/g, ' ').replace(/[.?!]+$/g, '').trim();
  const ordered = clean.slice().sort((a, b) => norm(b).length - norm(a).length);
  const res = [];
  for (const p of ordered) {
    const pn = norm(p);
    if (pn.length < 2) continue;
    const dup = res.some((q) => norm(q).indexOf(pn) >= 0);
    if (!dup) res.push(p);
  }
  return res;
}

/** Значимые слова темы: без стоп-слов и короче трёх букв. */
const STOP = new Set(['что', 'как', 'где', 'кто', 'чем', 'чём', 'или', 'и', 'в', 'во', 'на', 'с', 'со', 'по', 'из', 'для', 'это', 'этой', 'этого', 'если', 'бы', 'ли', 'же', 'мне', 'меня', 'тебя', 'ты', 'вы', 'нам', 'всё', 'все', 'при', 'о', 'об', 'про', 'до', 'от', 'за', 'под', 'над', 'к', 'у', 'без', 'после', 'перед', 'какой', 'какая', 'какие', 'сколько', 'нужно', 'надо', 'можно', 'будет', 'есть', 'они', 'оно', 'она', 'этом', 'этот', 'такой', 'такие', 'когда', 'почему', 'зачем', 'какое']);
/* Глаголы-инструкции из перечисления («сравни», «объясни») — не тема: в ответе их
   обычно нет, и каждый съедал треть покрытости, делая полный ответ неполным. */
const INSTRUCTION = new Set(['посчитай', 'сравни', 'объясни', 'опиши', 'перечисли', 'проверь', 'покажи', 'напиши', 'сделай', 'найди', 'укажи', 'распиши', 'предложи', 'выбери', 'выбрать', 'расскажи', 'приведи', 'дать', 'дай', 'подбери']);

/** Слово значимо: не мусор из повторов одной буквы, достаточно длинно или число. */
function meaningful(w) {
  if (!w) return false;
  if (/^\d+$/.test(w)) return w.length >= 1;   /* «2+2» — числа и есть смысл вопроса */
  if (w.length < 4) return false;              /* «KV» в два знака темой не считается */
  /* «аааа» — не слово: одна и та же буква на всю длину. */
  return new Set(Array.from(w)).size > 1;
}

/** Значимые слова темы. Знаки препинания снимаются ДО разбора: иначе «Postgres?»
    не совпадал с «Postgres» в ответе, и тема считалась нераскрытой. */
export function keywords(point) {
  const toks = String(point || '')
    .toLowerCase()
    /* Маркер пункта в начале («1)», «-») — не часть темы. */
    .replace(/^\s*(?:\d{1,2}[.)]|[-*•])\s+/u, ' ')
    .replace(/[^0-9a-zа-яё\-_\s]/giu, ' ')
    .split(/\s+/u)
    .map((w) => w.trim())
    .filter(meaningful);
  const kws = toks.filter((w) => !STOP.has(w) && !INSTRUCTION.has(w));
  /* Все слова оказались служебными («Что выбрать для мобильного приложения?» без
     глагола-инструкции) — тема всё равно должна с чем-то сравниваться, иначе она
     признавалась бы раскрытой всегда. */
  return kws.length ? kws : toks;
}

/** Доля значимых слов темы, которые дошли до ответа. */
export function coveredShare(point, reply) {
  /* Ключевые слова уже приводятся к нижнему регистру, но сама тема — нет:
     без этого «SQLite» из вопроса не находился в ответе, где он написан так же. */
  const kws = keywords(String(point || '').toLowerCase());
  if (!kws.length) return 1;
  const r = String(reply || '').toLowerCase();
  let hit = 0;
  for (const w of kws) {
    /* Основа слова: «договор» виден и в «договоре», «аренда» — в «аренду». */
    const stem = w.slice(0, Math.max(4, w.length - 2));
    if (r.indexOf(stem) >= 0) hit++;
  }
  return hit / kws.length;
}


/* ─────────────────────────── точный счёт ─────────────────────────── */

const NUM_WORDS = { 'одно': 1, 'один': 1, 'одного': 1, 'два': 2, 'две': 2, 'двух': 2, 'три': 3, 'трёх': 3, 'трех': 3, 'четыре': 4, 'четырёх': 4, 'четырех': 4, 'пять': 5, 'пяти': 5, 'шесть': 6, 'шести': 6, 'семь': 7, 'семи': 7, 'восемь': 8, 'восьми': 8, 'девять': 9, 'девяти': 9, 'десять': 10, 'десяти': 10, 'одним': 1, 'двумя': 2, 'тремя': 3, 'четырьмя': 4, 'пятью': 5, 'шестью': 6, 'семью': 7 };
const plainWords = (x) => String(x || '').replace(/[`*_#>«»"“”„]/g, ' ').replace(/[—–-]{1,2}(?=\s)/g, ' ').trim().split(/\s+/).filter((w) => /[A-Za-zА-Яа-яЁё0-9]/.test(w));
/**
 * «Ровно N слов / пунктов / предложений» — сверка кодом. Возвращает зацепку словами
 * или ''. Только явное «ровно / из N / в N» — «напиши 5 советов» без «ровно» не трогаем:
 * там число — ориентир, а не условие.
 */
export function exactCountIssue(text, reply) {
  const t = String(text || '').toLowerCase();
  let m = t.match(/(?:ровно|строго|из|в)\s+(\d{1,2}|[а-яё]+)\s+(слов(?:о|а|ом|ами)?|пункт(?:а|ов)?|предложени(?:й|я|е|ем|ями))(?![а-яё])/i);
  /* «ровно 3 фрукта списком» — любое существительное, если ответ — список */
  if (!m) {
    const g = t.match(/(?:ровно|строго)\s+(\d{1,2}|[а-яё]+)\s+[а-яё]+/i);
    if (g && /^\s*(?:\d{1,2}[.)]|[-*•])\s+/m.test(String(reply || ''))) m = [g[0], g[1], 'пункт'];
  }
  if (!m) return '';
  /* «из одного пункта» в просьбе о записке — описание, а не счёт: без «ровно» верим
     только «из N слов» (предложение заданной длины). */
  if (!/^(?:ровно|строго)/.test(m[0]) && !/^слов/.test(m[2])) return '';
  const n = /^\d+$/.test(m[1]) ? Number(m[1]) : NUM_WORDS[m[1]];
  if (!n || n > 50) return '';
  const r = String(reply || '').trim();
  if (!r) return '';
  let got = 0;
  if (/^слов/.test(m[2])) {
    /* считаем первое предложение/строку — тот ответ, о котором просили */
    const lines = r.split('\n').map((x) => x.trim()).filter(Boolean);
    got = plainWords(lines.length === 1 ? lines[0] : lines[0]).length;
  } else if (/^пункт/.test(m[2])) {
    got = r.split('\n').filter((x) => /^\s*(?:\d{1,2}[.)]|[-*•])\s+/.test(x)).length;
  } else {
    got = r.replace(/\n+/g, ' ').split(/(?<=[.!?…])\s+/).filter((x) => /[А-Яа-яЁёA-Za-z]/.test(x)).length;
  }
  if (got === n) return '';
  const unit = /^слов/.test(m[2]) ? 'слов' : /^пункт/.test(m[2]) ? 'пунктов' : 'предложений';
  return 'просили ровно ' + n + ' ' + unit + ', в ответе ' + got;
}

