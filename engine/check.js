/**
 * Ответ обещал структуру и не принёс её: «вот план:», «шаги:», «список:», «пример:» —
 * и дальше пусто или одна строка. Это тот случай, который глазами видно сразу, а
 * слой раньше не видел вовсе.
 */
export function promisedButEmpty(reply) {
  const r = String(reply || '');
  /* `\b` с кириллицей не работает (см. engine/depth.js), а пробел после
     двоеточия необязателен: «Вот план:» и есть обещание без продолжения. */
  const m = /(?:^|\n)[^\n]{0,60}?(план|шаги|список|пример|варианты|итак|вывод|структура)\s*[:—-]\s*([^\n]*)/iu.exec(r);
  if (!m) return '';
  const label = (m[1] || '').toLowerCase();
  const after = String(m[2] || '').trim();
  const tail = r.slice(m.index + m[0].length).trim();
  /* Обещание в конце ответа без продолжения — тоже зацепка. */
  if (!after && tail.length < 20) return 'обещан «' + label + '» без продолжения';
  if (after && after.length < 3 && tail.length < 20) return 'обещан «' + label + '» без продолжения';
  /* Перечисление обещано — пунктов должно быть больше одного. */
  if (/(план|шаги|список|варианты|структура)/.test(label)) {
    const items = (after + '\n' + tail).match(/(?:^|\n)\s*(?:\d+[.)]|[-*•])\s+\S/g) || [];
    if (items.length < 2 && (after + tail).length < 80) return 'обещан «' + label + '», а пунктов меньше двух';
  }
  return '';
}

/** Ответ обрывается на середине: незакрытая скобка/кавычка или висячий союз. */
export function looksCut(reply) {
  const r = String(reply || '').trimEnd();
  if (!r) return false;
  /* Незакрытая пара — зацепка на любом长度 ответа: «(a + b» обрывается и в коротком
     ответе. Порог длины оставлен только висячему союзу: «и» в конце короткой
     реплики («Да.» → «Да и») — ещё не обрыв. */
  const open = (r.match(/[([]/g) || []).length;
  const close = (r.match(/[)\]]/g) || []).length;
  if (open - close >= 1) return true;
  const quotes = (r.match(/«/g) || []).length - (r.match(/»/g) || []).length;
  if (quotes >= 1) return true;
  /* Висячий союз — обрыв только на связном тексте: «потому что» в конце короткой
     реплики («Да.» → «Да и») ещё не значит, что ответ оборвался. */
  return r.length > 20 && /(?:\s(?:и|или|но|а|что|котор|потому\s+что|так\s+как|где|когда|если))$/iu.test(r);
}

/* ─────────────────────────── отказ вместо ответа ─────────────────────────── */

const REFUSAL = /(я\s+не\s+могу|не\s+могу\s+(?:ответить|помочь|выполнить)|как\s+(?:искусственный\s+интеллект|языковая\s+модель|ИИ)|у\s+меня\s+нет\s+(?:доступа|возможности)|я\s+всего\s+лишь\s+модель|извините,\s+но\s+я)/i;

/* 0.236: тонкие формы самоцензуры, которые длиннее короткого отказа и проходят
   первый фильтр: подмена темы («не буду описывать… вместо этого расскажу в общих
   чертах»), обрыв художественной сцены («оставим за кадром», «опустим подробности»),
   непрошеные возрастные ворота и морализаторская лекция вместо сути. */
const BAIT_SWITCH_RE = /(?:я\s+)?не\s+(?:могу|буду|стану|вправе)\s+(?:писать|описывать|создавать|генерировать|продолжать|выполнять|приводить|раскрывать)\s+[^.!?\n]{3,95}[.!?]\s*(?:вместо\s+этого|однако\s+(?:я\s+)?могу\s+(?:предложить|рассказать\s+в\s+общих|объяснить\s+общ)|могу\s+предложить\s+более\s+(?:безопасн|нейтральн|сдержан))/i;
const FADE_TO_BLACK_RE = /(?:остальн(?:ое|ые\s+подробности)|дальнейш(?:ее|ие\s+подробности)|интимн[а-яё]+\s+подробности|детали\s+сцены)\s+(?:оставим|опустим|останутся)\s*(?:за\s+кадром|без\s+описания)?|оставим\s+(?:это\s+|подробности\s+|дальнейшее\s+)?за\s+кадром|опустим\s+(?:интимные\s+|лишние\s+|откровенные\s+)?подробности|дальше\s+(?:представьте|додумайте)\s+сами|\[(?:сцена\s+обрывается|цензура|вырезано\s+цензурой)\]/i;
const AGE_GATE_CHECK_RE = /(?:подтверди(?:те)?|уточни(?:те)?|укажи(?:те)?),?\s+(?:пожалуйста,?\s+)?(?:что\s+)?(?:тебе|вам)\s+(?:уже\s+)?(?:есть|исполнилось)\s+18|(?:тебе|вам)\s+(?:уже\s+)?(?:есть|исполнилось)\s+18\s*(?:лет|\?)|(?:этот|данный)\s+(?:контент|материал|разговор)\s+(?:доступен|предназначен)\s+только\s+(?:для\s+)?(?:совершеннолетних|лиц\s+старше\s+18)/i;
const MORAL_LECTURE_RE = /(?:важно|необходимо|следует)\s+помнить\s+о\s+(?:моральн[а-яё]+|этическ[а-яё]+|нравственн[а-яё]+)\s+(?:нормах|ответственности|принципах|границах)|с\s+(?:этической|моральной|нравственной)\s+точки\s+зрения\s+(?:такие|подобные)\s+(?:действия|темы|запросы)\s+неприемлем|прежде\s+всего\s+(?:стоит|следует)\s+задуматься\s+о\s+(?:моральн|нравственн|этическ)/i;

/** Ответ — отказ или отписка, хотя вопрос не про запретное. */
export function isRefusalAnswer(reply, text) {
  const r = String(reply || '').trim();
  const t = String(text || '');
  /* Формулы отказа — всегда зацепка: на вопрос длиннее фразы «не могу» так не
     отвечают. */
  if (REFUSAL.test(r.slice(0, 240)) && t.length > 20) return true;
  /* Пустота вместо ответа — тоже. А вот короткий ответ БЕЗ слов отказа — не
     отписка: «Да, верно.» и «4» законны, и прежний порог вешал на них зацепку
     «вместо ответа — отказ», которая стоила лишнего прогона модели. */
  if (r.length === 0 && t.trim().length > 0) return true;
  return false;
}

/**
 * Скрытый уход от ответа (0.236): подмена темы, обрыв сцены «за кадром»,
 * возрастной допрос или непрошеное нравоучение на безопасном запросе.
 */
export function evasionIssue(text, reply) {
  const r = String(reply || '').trim();
  const t = String(text || '').trim();
  if (!r || !t || isHardDanger(t)) return '';
  if (isMetaFilterRefusal(r, t)) return 'вместо ответа — лекция о фильтрах языковой модели';
  if (BAIT_SWITCH_RE.test(r)) return 'вместо прямого ответа — подмена или уход в общие слова';
  if (!/за\s+кадром|опусти[а-яё]*\s+подробност/i.test(t) && FADE_TO_BLACK_RE.test(r)) {
    return 'сцена оборвана самоцензурой («за кадром» / «опустим подробности»)';
  }
  if (!/возраст|18\s*лет|совершеннолет/i.test(t) && AGE_GATE_CHECK_RE.test(r)) {
    return 'вместо ответа — непрошеная проверка возраста';
  }
  if (r.length < 700 && !/этик|морал|нравствен|законн/i.test(t) && MORAL_LECTURE_RE.test(r)) {
    return 'вместо ответа по существу — непрошеное нравоучение';
  }
  if (isPoliteRefusal(r, { prompt: t })) return 'вместо ответа — отказ или отписка';
  return '';
}

/* ─────────────────────────── сам разбор ─────────────────────────── */

/**
 * Найти зацепки: чем ответ не соответствует вопросу.
 *
 * @returns {{notes: string[], points: number, covered: number, share: number}}
 *   notes — причины словами (их видит человек), points/covered — сколько тем
 *   вопроса и сколько из них дошло, share — доля чисел инструмента в ответе.
 */
export function findIssues(input) {
  const i = input || {};
  const cfg = cfgOf(i.env);
  const text = String(i.text || '');
  const reply = String(i.reply || '');
  const notes = [];
  const out = { notes, points: 0, covered: 0, share: 1, refused: false, evasion: false, cut: false };

  if (!cfg.on || !reply.trim()) return out;
  /* На отказе движка проверять нечего: там нет ответа, там причина. */
  if (i.ok === false) return out;

  /* 1) отказ, отписка или самоцензурный уход вместо ответа */
  if (isRefusalAnswer(reply, text)) {
    out.refused = true;
    out.evasion = !isHardDanger(text);
    notes.push('вместо ответа — отказ или отписка');
  } else {
    const ev = evasionIssue(text, reply);
    if (ev) {
      out.evasion = true;
      notes.push(ev);
    }
  }

  /* 2) данные инструмента не дошли до ответа.
     Арифметику правило НЕ трогает: блок калькулятора — это «24 - 8 - 5 = 11», и
     требовать от ответа всех трёх чисел значит вешать зацепку на верный ответ
     «11» и жечь квоту на досыл (поймано проверкой G7 в council.test.js: совет
     выключен бюджетом, а второй вызов всё равно уходил). Точность счёта уже
     доказана самим инструментом. */
  const nums = toolNumbers(i.block);
  out.share = numberShare(nums, reply);
  const tools = Array.isArray(i.tools) ? i.tools : [];
  const counted = tools.indexOf('calc') >= 0 || /\[Инструмент: Калькулятор\]/i.test(String(i.block || ''));
  /* Поиск в интернете приносит сниппеты, а в них полно случайных чисел (население,
     даты, площадь). На «Столица Франции?» правило требовало этих чисел, досыл
     переписывал верный ответ «Париж» в «Население 2 102 650…» без самого Парижа.
     Для поиска числа обязательны, только если вопрос сам про число. */
  const searched = tools.indexOf('web-search') >= 0;
  const asksNumber = ASKS_NUMBER.test(text);
  /* То же для любого инструмента: если вопрос не про число, инструмент мог сработать
     мимо (так «ре-КУРС-ия» звала курс валют), и требовать его чисел — портить ответ.
     Погода — исключение: там числа и есть ответ, даже на «что надеть?». */
  const weather = tools.indexOf('weather') >= 0;
  if (!counted && (asksNumber || weather) && nums.length >= 2 && out.share < cfg.numberShare) {
    notes.push('данные инструмента не дошли до ответа (' + Math.round(out.share * 100) + '% чисел)');
  }

  /* 3) обещанная структура без содержания */
  const promised = promisedButEmpty(reply);
  if (promised) notes.push(promised);

  /* 4) оборванный хвост */
  if (looksCut(reply)) {
    out.cut = true;
    notes.push('ответ обрывается на середине');
  }

  /* 4б) точный счёт, заданный человеком: «ровно 5 слов», «ровно 3 пункта». Это
     проверяется кодом без догадок — а модели в нём промахиваются (MeTiger Bench i7:
     «предложение ровно из 5 слов» → «Кошка спит на окне.», 4 слова). */
  const exact = exactCountIssue(text, reply);
  if (exact) notes.push(exact);

  /* 5) спросили несколько вещей — ответили не на все */
  const points = askedPoints(text);
  out.points = points.length;
  if (points.length >= cfg.minQuestions) {
    let covered = 0;
    const missed = [];
    for (const p of points) {
      if (coveredShare(p, reply) >= 0.5) covered++;
      else missed.push(p);
    }
    out.covered = covered;
    if (covered < points.length) {
      notes.push('спрошено ' + points.length + ', отвечено на ' + covered
        + (missed.length ? ' (без ответа: ' + missed.slice(0, 2).map((m) => m.slice(0, 40)).join('; ') + ')' : ''));
    }
  }

  /* 6) свежесть источников против утверждений о свежести (0.231) */
  const stale = freshnessIssue(reply, i.sources, i.now);
  if (stale) notes.push(stale);

  /* 7) число источников словами не сходится с плашками под ответом */
  const miscount = sourceCountIssue(reply, Array.isArray(i.sources) ? i.sources.length : 0);
  if (miscount) notes.push(miscount);

  return out;
}

/**
 * Текст досыла для починки: вопрос, собственный ответ агента и зацепки словами.
 *
 * 0.231 — правка НА МЕСТЕ. Раньше здесь было «допиши только недостающее», и голова
 * так и делала: возвращала один абзац «Уточнение: …», а сервер ставил его вместо
 * всего ответа. В проде человек получил вместо ответа про React одну строку
 * «Уточнение: мои знания ограничены…». Теперь просим полный текст заново: ошибка
 * заменяется там, где стояла, а не приписывается хвостом после прочитанного.
 */
export function repairPrompt(input) {
  const i = input || {};
  const rawNotes = Array.isArray(i.notes) ? i.notes : [];
  const notes = rawNotes.map((n) => '— ' + n).join('\n');
  const ask = String(i.text || '').slice(0, 2000);
  const draft = String(i.reply || '').slice(0, 4000);
  const isEvasion = !!i.evasion || rawNotes.some((n) => /отказ|отписк|подмена|за кадром|нравоучени|возраст|фильтр/i.test(String(n || '')));
  /* 0.240: если черновик целиком состоял из отказа, подмены темы, возрастных ворот
     или лекции про фильтры ИИ, подставлять его под «Твой ответ:» нельзя — следующая
     голова вместо ответа начинает разбирать чужой отказ («Это отказала языковая
     модель…»). Сцену с «оставим за кадром» сохраняем, чтобы не потерять завязку. */
  const purePoison = isEvasion && !FADE_TO_BLACK_RE.test(draft) && (
    isRefusalAnswer(draft, ask || 'вопрос человека для проверки')
    || isPoliteRefusal(draft, { prompt: ask })
    || isMetaFilterRefusal(draft, ask)
    || BAIT_SWITCH_RE.test(draft)
    || AGE_GATE_CHECK_RE.test(draft)
  );
  if (purePoison) {
    return [
      'Дай прямой и полный ответ на запрос человека с нуля.',
      '',
      'Запрос человека:',
      ask,
      '',
      'Предыдущая попытка сорвалась в отказ или постороннюю отписку (' + (rawNotes.join('; ') || 'самоцензура') + ').',
      'Раскрой запрос прямо и до конца: без отказов, оговорок, возрастных проверок, морализаторства и без любых рассуждений о языковых моделях, фильтрах или ограничениях.',
      'Не пиши служебных пометок («Уточнение», «Правка», «Исправление»). В ответе верни только сам текст ответа.',
    ].join('\n');
  }
  const lines = [
    'Твой ответ на вопрос человека проверили и нашли несостыковки.',
    '',
    'Вопрос человека:',
    ask,
    '',
    'Твой ответ:',
    draft,
    '',
    'Что не так:',
    notes || '— зацепок нет',
    '',
    'Перепиши ответ ЦЕЛИКОМ — так, будто ты отвечаешь человеку впервые и уже знаешь, что было не так.',
    'Неверное место замени верным там же, где оно стояло, а недостающее добавь в нужный пункт.',
    'Не пиши отдельным абзацем «Уточнение», «Правка», «Исправление», «Примечание» и подобные служебные пометки: человек читает только ответ, а не историю его проверки.',
  ];
  if (isEvasion) {
    lines.push('Предыдущий вариант ушёл в самоцензуру, обрыв сцены или непрошеные поучения — убери любые отказы, оговорки и «оставим за кадром» и раскрой запрос прямо и до конца.');
  }
  lines.push(
    'Без извинений. Если исправлять нечего — верни ответ как есть.',
    'В ответе верни только сам текст ответа, без пояснений о том, что ты исправил.',
  );
  return lines.join('\n');
}

/* ─────────────────────── правка вместо приписки ─────────────────────── */

/* Служебные зачины, которыми голова начинает «правку»: «Уточнение:», «**Правка:**»,
   «Вот исправленный ответ:». Их не должно быть в тексте для человека. */
const SERVICE_HEAD = /^\s*(?:#{1,6}\s*)?(?:\*\*|__)?\s*(?:вот\s+)?(?:уточнени[ея]|правка|исправлени[ея]|исправленный\s+(?:ответ|вариант)|корректировка|поправка|обновлени[ея]|дополнени[е])\s*(?:\*\*|__)?\s*[:.—–-]\s*(?:\*\*|__)?\s*/i;
const SERVICE_PARA = /^\s*(?:#{1,6}\s*)?(?:\*\*|__)?\s*(?:уточнени[ея]|правка|исправлени[ея]|корректировка|поправка|обновлени[ея])(?![а-яё])/i;

/**
 * Снять с ответа служебные пометки о проверке: зачин «Уточнение:» в начале и
 * хвостовые абзацы-приписки после уже готового ответа. Текст, который целиком
 * состоял из уточнения, остаётся без зачина — решать, годится ли он, будет
 * `repairTake` по связи с исходным ответом.
 */
export function stripService(reply) {
  let text = String(reply || '').replace(/\r/g, '').trim();
  text = text.replace(SERVICE_HEAD, '');
  const paras = text.split(/\n{2,}/);
  /* Хвост-приписка: абзац начинается со служебного слова и стоит ПОСЛЕ ответа.
     Первый абзац не режем здесь — его зачин уже снят выше. */
  while (paras.length > 1 && SERVICE_PARA.test(paras[paras.length - 1])) paras.pop();
  return paras.join('\n\n').trim();
}

/** Значимые слова текста: грубая основа без служебных и совсем коротких слов. */
function significantWords(text) {
  const stop = new Set(['этот', 'этого', 'этом', 'котор', 'которые', 'которая', 'также', 'чтобы', 'потому', 'поэтому', 'можно', 'нужно', 'будет', 'были', 'было', 'если', 'когда', 'пока', 'только', 'очень', 'более', 'менее', 'через', 'после', 'перед', 'между', 'свой', 'свои', 'это', 'весь', 'всех', 'всё', 'есть', 'быть', 'как', 'для', 'при', 'или', 'над', 'под', 'про', 'без', 'что', 'чем']);
  const out = new Set();
  for (const raw of String(text || '').toLowerCase().split(/[^a-zа-яё0-9]+/i)) {
    if (raw.length < 4 || stop.has(raw)) continue;
    out.add(raw.length > 6 ? raw.slice(0, raw.length - 2) : raw);
  }
  return out;
}

/** Насколько переписанный текст повторяет исходный: доля его значимых слов. */
export function overlapShare(original, next) {
  const a = significantWords(original);
  if (!a.size) return 0;
  const b = significantWords(next);
  let hit = 0;
  for (const w of a) if (b.has(w)) hit++;
  return hit / a.size;
}

/**
 * Принять ли досыл починки вместо текущего ответа.
 *
 * Досыл обязан быть ПЕРЕПИСАННЫМ ответом, а не припиской. Признак приписки:
 * текст почти не повторяет слов исходного ответа и заметно короче его — значит
 * голова, как в проде 0.230, вернула «Уточнение: …» вместо ответа. Такой текст
 * не заменяет написанное: человек уже прочитал ответ, и терять его нельзя.
 *
 * @returns {{ reply: string, why: string }} reply пуст — починку не принимаем.
 */
export function repairTake(original, fixed, opts) {
  const o = opts || {};
  const askText = String(o.text || '');
  const clean = stripService(fixed);
  const was = String(original || '').trim();
  if (!clean) return { reply: '', why: 'починка пришла пустой — ответ оставлен как есть' };
  if (clean.length < 40) return { reply: '', why: 'починка короче ответа — ответ оставлен как есть' };
  /* Починка сама сорвалась в отказ или уход от темы — не подменяем написанное отказом. */
  if (isRefusalAnswer(clean, askText || 'вопрос человека для проверки') || isPoliteRefusal(clean, { prompt: askText }) || (askText && evasionIssue(askText, clean))) {
    return { reply: '', why: 'починка снова ушла в отказ — ответ оставлен как есть' };
  }
  /* Служебный абзац, снятый целиком, — приписка даже при совпадении слов:
     модель пересказала зацепку вместо того, чтобы переписать ответ. */
  const raw = String(fixed || '');
  const onlyService = SERVICE_HEAD.test(raw.trim()) && !/\n\s*\n/.test(raw.trim()) && clean.length < was.length * 0.75;
  if (onlyService) return { reply: '', why: 'починка оказалась уточнением, а не новым ответом — ответ оставлен как есть' };
  /* Начало со служебного зачина при потере смысла исходного ответа — приписка:
     «Уточнение: …» поверх готового ответа. Проверяем до послабления для коротких
     ответов: именно короткий ответ и заменялся одной фразой «Уточнение». */
  if (SERVICE_HEAD.test(String(fixed || '').trim()) && overlapShare(was, clean) < 0.4) {
    return { reply: '', why: 'починка оказалась уточнением, а не новым ответом — ответ оставлен как есть' };
  }
  /* 0.236: если исходный ответ был самоцензурной отпиской или нравоучением, новый
     прямой ответ не обязан повторять слова отказа — он должен отвечать на вопрос. */
  if (o.evasion) {
    if (overlapShare(was, clean) >= 0.15 || (askText && overlapShare(askText, clean) >= 0.12) || clean.length >= Math.max(80, was.length * 0.75)) {
      return { reply: clean, why: '' };
    }
    return { reply: '', why: 'починка не связана с вопросом — ответ оставлен как есть' };
  }
  /* Слишком короткий исходный ответ — судить о связи не по чему: два слова дают
     случайное совпадение, и честная починка была бы отброшена. */
  if (significantWords(was).size < 6) return { reply: clean, why: '' };
  /* Короткая приписка к длинному ответу — не новый ответ, а хвост. */
  if (clean.length < was.length * 0.45 && overlapShare(was, clean) < 0.4) {
    return { reply: '', why: 'починка оказалась припиской — ответ оставлен как есть' };
  }
  /* Совсем не о том: голова ушла в сторону, текст не связан с ответом. */
  if (overlapShare(was, clean) < 0.2) {
    return { reply: '', why: 'починка не связана с ответом — ответ оставлен как есть' };
  }
  return { reply: clean, why: '' };
}

/* ─────────────────────── свежесть источников ─────────────────────── */

const FRESH_CLAIM = /(последн(?:яя|ей|юю|ие)\s+верси|сам(?:ый|ая|ые)\s+свеж|свежие\s+данн|актуальн\w*\s+(?:на|в)\s+\d{4}|по\s+состоянию\s+на|на\s+сегодня|на\s+данный\s+момент|сейчас\s+(?:вышл|доступн|актуальн)|только\s+что\s+вышл)/i;
const OLD_MARK = new RegExp('(устарел|стар(?:ая|ый|ые|о)(?![а-яё])|(?<![а-яё])давн|не\\s+самы[ех]\\s+свеж|данные\\s+(?:за|на)\\s+\\d{4}|актуальн\\w*\\s+(?:на|за)\\s+\\d{4}|на\\s+\\d{4}\\s+год)', 'i');

/** Год из даты источника: '2020-03-01' → 2020. */
function yearOf(dateISO) {
  const m = /(\d{4})/.exec(String(dateISO || ''));
  return m ? Number(m[1]) : 0;
}

/**
 * Свежесть в ответе против свежести источников (0.231).
 *
 * Человек спрашивал «что нового», а статья 2020 года шла в ответе как свежая.
 * Проверка узкая, чтобы не цеплять честные ответы: зацепка появляется, только
 * когда ответ сам заявляет свежесть («последняя версия», «сейчас вышла»,
 * «актуально на 2026»), среди источников есть давний, и год этого источника в
 * ответе не назван. Нет дат — нет и зацепки: судить не по чему.
 */
export function freshnessIssue(reply, sources, now) {
  const r = String(reply || '');
  if (!FRESH_CLAIM.test(r)) return '';
  const today = Number(now) || Date.now();
  const dated = (Array.isArray(sources) ? sources : [])
    .map((s) => ({ year: yearOf(s && s.date), date: String((s && s.date) || '') }))
    .filter((s) => s.year >= 1995);
  if (!dated.length) return '';
  const old = dated.filter((s) => {
    const y = Number(s.date.slice(0, 4));
    const m = /^\d{4}-(\d{2})-(\d{2})$/.exec(s.date);
    const t = m ? Date.UTC(y, Number(m[1]) - 1, Number(m[2])) : Date.UTC(y, 0, 1);
    return (today - t) / 86400000 >= 545;
  });
  if (!old.length) return '';
  /* Год в ответе назван — человек видит, о каком времени речь, и «последняя
     версия» уже не выдаёт старое за свежее. Ложная зацепка тут дороже пропуска:
     на проде она переписала верный ответ про Python 3.9 из-за фразы «последняя
     версия с полноценной поддержкой» (0.231). */
  if (/(?:19|20)\d{2}/.test(r)) return '';
  const oldest = old.reduce((a, b) => (b.year < a.year ? b : a));
  if (OLD_MARK.test(r)) return '';
  return 'источник от ' + oldest.year + ' года подан как свежий — нужен год или более новый источник';
}

/** Ответ говорит «нашёл N источников», а плашек под ним другое число. */
export function sourceCountIssue(reply, count) {
  const n = Number(count) || 0;
  if (n < 1) return '';
  const m = /(?:наш[её]л|найдено|использовал|проверил|из)\s+(\d{1,2})\s+источник/i.exec(String(reply || ''));
  if (!m) return '';
  const said = Number(m[1]);
  if (said === n) return '';
  return 'сказано «' + said + ' источников», а под ответом ' + n;
}

/**
 * Принять решение: что сказать человеку и нужна ли починка.
 *
 * @returns {{on: boolean, notes: string[], needFix: boolean, why: string}}
 */
export function decide(input) {
  const i = input || {};
  const cfg = cfgOf(i.env);
  const found = findIssues(i);
  const notes = found.notes.slice(0, 3);
  if (!cfg.on || !notes.length) {
    return { on: cfg.on, notes: [], needFix: false, evasion: false, why: '' };
  }
  /* Явный бюджет хода сильнее общего env: расширенное рассуждение (0.212)
     разрешает второй/третий проход только своей задаче, а не всему трафику. */
  const budget = Number.isFinite(Number(i.budget)) && i.budget != null
    ? Math.min(3, Math.max(0, Math.floor(Number(i.budget))))
    : cfg.budget;
  const needFix = cfg.fix && (i.spent || 0) < budget;
  return {
    on: true,
    notes,
    needFix,
    evasion: !!found.evasion,
    why: needFix ? notes.join('; ') : notes.join('; ') + ' (починка не разрешена бюджетом)',
  };
}

/** Строка для подписи под ответом: её читает человек, поэтому она без кодов. */
export function lineOf(check) {
  const c = check || {};
  if (!c || !c.notes || !c.notes.length) return '';
  const head = c.fixed ? ' · самопроверка: исправлено' : ' · самопроверка: ';
  return head + c.notes.join('; ');
}
