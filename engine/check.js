/** Числа, которые принёс инструмент (блок «[Инструмент: …]» в сообщении). */
export function toolNumbers(block) {
  const b = String(block || '');
  if (b.indexOf('[Инструмент') < 0) return [];
  const out = [];
  for (const m of b.matchAll(/-?\d[\d\s\u00a0\u202f]*(?:[.,]\d+)?/gu)) {
    const n = m[0].replace(/[\s\u00a0\u202f]/gu, '').replace(',', '.');
    /* Дробные и крупные целые: «1» и «2» из заголовка инструмента ничего не значат. */
    if (n.indexOf('.') >= 0 || Math.abs(Number(n)) >= 10) out.push(n);
  }
  return Array.from(new Set(out)).slice(0, 20);
}

/** Доля чисел инструмента, которая дошла до ответа (сравниваем нормализованно). */
export function numberShare(nums, reply) {
  if (!nums || !nums.length) return 1;
  const r = String(reply || '').replace(/[\s\u00a0\u202f]/gu, '').replace(/,/g, '.');
  let hit = 0;
  for (const n of nums) if (r.indexOf(n) >= 0) hit++;
  return hit / nums.length;
}

