/**
 * Нужен ли для этого вопроса интернет (0.168).
 *
 * Владелец: «Убери кнопку поиска, поиск будет автоматическим, смотря если нужно
 * искать в интернете, зависит от запроса». Значит решать должен движок, и решать
 * по-настоящему: не по одному слову «погугли», а по смыслу вопроса.
 *
 * Правило простое и объяснимое. Вопросу нужен интернет, если он про то, что
 * МЕНЯЕТСЯ: курсы, цены, погода, новости, версии, релизы, кто сейчас у власти,
 * что случилось. Или если человек прямо попросил поискать. Вопросу НЕ нужен
 * интернет, если он про то, что не меняется: определения, объяснения, код,
 * перевод, счёт, творчество.
 *
 * Почему это не «одно большое регулярное выражение», а счёт очков: у ошибок тут
 * разная цена. Лишний поиск — это секунды ожидания и чужая квота. Пропущенный
 * поиск — это уверенный ответ устаревшими данными (именно так и родилась 0.163).
 * Поэтому очки: прямое «поищи» перевешивает всё; «динамические» слова дают два
 * очка; маркеры свежести — одно (сами по себе они не решают: «план на сегодня»
 * интернета не требует); «что такое», «напиши», «переведи» — минус пять.
 * Порог — два очка. Каждое решение можно объяснить одним словом-причиной, и это
 * специально: причину удобно показать в отладке и трудно «подкрутить» вслепую.
 */

/** Прямая просьба поискать: она важнее любых оговорок. */
const EXPLICIT = /погугл|поищи|поиск[а-яё]*\s+(?:в\s+)?(?:интернете|сети|сети)|найди\s+(?:мне\s+)?(?:в\s+)?(?:интернете|сети|инфу|информацию|данные)|проверь\s+(?:в\s+)?(?:интернете|сети|гугле)|погляди\s+(?:в\s+)?(?:интернете|сети)|search\s+the\s+web|look\s+(?:it\s+)?up\s+online|google\s+it/i;

/** То, что меняется: курсы, цены, погода, новости, матчи, рейтинги и прочее живое. */
const DYNAMIC = [
  /курс|валют|котиров|бирж|акци[йяи]|биткоин|\bbtc\b|эфир(?:иум)?|\beth\b/,
  /цен[аыу]|цены|тариф|абонплат|стоимость|сколько\s+(?:сейчас\s+)?сто(?:ит|ят)|подорожал|подешевел/,
  /погод|температур[аы]\s+(?:за\s+окном|сейчас|сегодня)|осадк|прогноз\s+погоды/,
  /новост|что\s+случилось|что\s+произошло|происшеств/,
  /пробк|расписани|билет|авиабилет|рейс|электричк/,
  /матч|счёт\s+(?:матча|игры)|счет\s+(?:матча|игры)|результат[а-яё]*\s+(?:матч|игр|выбор|голосован)|турнирн|чемпионат|олимпиад/,
  /рейтинг|опрос|инфляц|ключев[а-яё]*\s+ставк|ставка\s+рефинансирован|безработиц|ввп|мрот|прожиточн|населен|перепис|сколько\s+(?:людей|народу|жителей|человек)\s+(?:жив|в\s)/,
  /президент|президента|министр|губернатор|глав[аы]\s+(?:города|страны|региона)|мэр|правящ/,
  /последн[а-яё]*\s+(?:верси|обновлен|релиз|модел|постановлен|новост)|новая\s+версия|какая\s+версия|[а-яё]*версия\s+[а-яё]|обновил[а-яё]*\s+до|выпустил[аи]?\s+версию/,
  /когда\s+вы(?:йдет|ш[её]л|шла|шло|пустят|появится)|дата\s+выхода|релиз\s+(?:состоится|намечен)/,
  /выиграл|победил|проиграл|занял\s+первое\s+место/,
  /официальн[а-яё]*\s+сайт|официальн[а-яё]*\s+источник/,
  /что\s+нов(?:ого|енького)|что\s+изменилось|какие\s+новости/
];

/** Маркеры «мне нужен свежий ответ»: сами по себе слабые, но усиливают динамику. */
const FRESH = /сегодня|сейчас|вчера|позавчера|на\s+этой\s+неделе|в\s+этом\s+(?:году|месяце)|за\s+последн|последн|свеж|актуальн|текущ|на\s+данный\s+момент|(?:^|\D)20(?:2[4-9]|3\d)(?:\D|$)/i;

/** Про то, что не меняется: тут поиск только мешает и тратит чужую квоту. */
const EVERGREEN = /что\s+такое|кто\s+так(?:ой|ая|ое)|объясни|объясните|в\s+ч[её]м\s+разниц|как\s+(?:работает|устроен|устроено|готовится)|почему\s+(?:небо|луна|солнце)|напиши|составь|сделай|придумай|переведи|сколько\s+будет\s+[\d(]|посчитай|реши\s+(?:задач|уравнен)|анекдот|шутк|стих|поздравлен|сценарий|сочинени|реферат|конспект|план\s+на\s+(?:день|неделю|месяц)|распорядок/i;

/**
 * @returns {{ need: boolean, score: number, why: string }}
 *   need — включать ли автоматический веб-поиск; why — одна причина словами.
 */
export function needsWeb(text) {
  const t = String(text || '');
  if (!t.trim()) return { need: false, score: 0, why: 'пусто' };
  if (EXPLICIT.test(t)) return { need: true, score: 10, why: 'попросили поискать' };
  let score = 0;
  let why = '';
  for (const re of DYNAMIC) {
    if (re.test(t)) { score += 2; if (!why) why = 'данные меняются'; }
  }
  if (FRESH.test(t)) { score += 1; if (!why) why = 'нужна свежесть'; }
  const evergreen = EVERGREEN.test(t);
  if (evergreen) score -= 5;
  if (score < 2) {
    /* Причину называем честно: «вечный» вопрос, «мало свежести» и «ничего живого
       не видно» — это три разных случая, и по подписи видно, какой именно. */
    const whyNot = evergreen
      ? 'это про то, что не меняется'
      : (why ? 'нужна свежесть, но живых данных не видно' : 'нет признаков свежих данных');
    return { need: false, score, why: whyNot };
  }
  return { need: true, score, why };
}

/** Короткая подпись для отладки: почему поиск включился (или нет). */
export function webReason(text) {
  const r = needsWeb(text);
  return `${r.need ? 'поиск' : 'без поиска'} (${r.score}): ${r.why}`;
}
