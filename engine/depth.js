/**
 * 🧭 Судья глубины — «размышлять глубже» решает агент, а не кнопка (0.123).
 *
 * Зачем этот слой. До 0.123 глубина ответа зависела от переключателя в меню «+»:
 * человек сам должен был знать, где цена ошибки выше цены секунды. Это не агентская
 * работа, а перекладывание решения движка на того, кто за помощью и пришёл. Замер
 * на проде (9 октября 2026) показал и вторую половину правды: на вопросах, которые
 * классификатор и так понял верно («докажи, что √2 иррационально», «что лучше kotlin
 * или swift»), переключатель не менял модель вовсе — `reasoning/smart` и
 * `openai/gpt-oss-120b` в обоих прогонах, 14,9 с против 14,3 с. То есть кнопка
 * работала ровно там, где классификатор ошибался, и это её настоящий размер.
 *
 * Что делает слой. Читает САМ вопрос (и что уже известно о задаче) и возвращает
 * решение словами: глубже или нет, почему, и сколько голов звать в совет. Решение
 * видно в подписи под ответом, а не спрятано: «глубже: доказательство или вывод» —
 * так же, как совет голов пишет «сошлись 3/3» или «пропущено: <причина>».
 *
 * Чем решает. Правилами на JS, а не вызовом модели. Три причины:
 *   • бесплатно: лишняя голова на каждый запрос — это квота провайдера, а проект
 *     живёт на бесплатных ключах;
 *   • быстро: судья стоит микросекунды и отрабатывает до выбора пула;
 *   • проверяемо: правило можно показать пальцем и завалить тестом, а «модель
 *     решила» — нельзя (см. test/depth.test.js).
 * Модель здесь появится позже и точечно: там, где правила спорят (слой 2 плана —
 * самопроверка ответа), а не на каждом запросе.
 *
 * Чего слой НЕ делает: не включает поиск в сети (это `webSearch`), не созывает совет
 * сам (он только советует число голов, решает `runCouncils`), не выбирает модель
 * (это `route.modelsFor` по флагу `deep`). Один слой — одно дело.
 */

/** Порог: сколько очков нужно, чтобы поднять глубину. */
export const DEPTH_THRESHOLD = 2;

/** Потолок очков: длинный вопрос не должен набирать бесконечно. */
const MAX_SCORE = 99;

/**
 * Граница слова по-русски — и почему здесь нет `\b`.
 *
 * `\b` в JavaScript считается от `\w`, а `\w` — это только `[A-Za-z0-9_]`.
 * Кириллица для него НЕ буквы, поэтому `/\b(докаж)/.test('докажи')` === false:
 * примета не срабатывала бы ни разу, а слой молча отвечал «примет глубины нет».
 * Поймано первой же пробой test/depth.test.js (Г1).
 *
 * Lookbehind `(?<![\p{L}])` задачу решает, но в движке он больше нигде не
 * использован, а падение разбора регулярки убило бы ВЕСЬ ответ, а не одну примету.
 * Поэтому граница считается отдельно и безопасно: регулярка ищет подстроку
 * (латинские ветки — со своим честным `\b`), а `wordHit` смотрит на СОСЕДА СЛЕВА
 * от найденного места через `\p{L}`. Сосед-буква — значит это кусок другого слова
 * («недоказуемо», «риски»).
 *
 * Справа граница не проверяется намеренно: приметы написаны основами
 * («докаж», «договор», «стратеги»), а русское окончание — часть того же слова.
 * Проверка справа ломала ровно то, ради чего слой существует: «докажи, что…»
 * и «в договоре» не совпадали из-за запятой и окончания.
 */
export function wordHit(re, t) {
  const s = String(t || '');
  const r = new RegExp(re.source, re.flags.indexOf('g') >= 0 ? re.flags : re.flags + 'g');
  let m;
  while ((m = r.exec(s)) !== null) {
    if (m[0] === '') { r.lastIndex++; continue; }
    const before = s.slice(Math.max(0, m.index - 1), m.index);
    if (!/[\p{L}\p{N}_]/u.test(before)) return true;
  }
  return false;
}

/** Примета: регулярка + как её искать (по границе слова или просто подстрокой). */
function mark(id, weight, why, re, whole) {
  return { id, weight, why, re, word: whole !== false, test: (t) => (whole === false ? re.test(t) : wordHit(re, t)) };
}

/* ───────────────────────────── приметы глубины ─────────────────────────────
   Вес 2 — примета сама по себе достаточна. Вес 1 — половина: такие работают
   парами («сравни» + «чем отличается») или вместе с длиной вопроса.
   Каждая примета названа словами для человека: причина уезжает в подпись ответа,
   поэтому она обязана читаться, а не быть номером правила. */
export const RULES = [
  mark('proof', 2, 'доказательство или вывод',
    /(докаж|доказательств|обоснуй|обоснован|строго\s+(?:докажи|покажи)|выве(?:ди|дите|дём|дем|сти)\s+(?:формулу|закон|уравнение))/iu),

  mark('plan', 2, 'план из нескольких шагов',
    /(план|по\s+шагам|пошагов|с\s+чего\s+начать|дорожн(?:ая|ой)\s+карт|стратеги(?:я|ю|и)|этапы\s+внедрени|порядок\s+действий|\broadmap\b)/iu),

  /* «иск» — только целым словом: основа ловила бы «риски» и «искусство». */
  mark('stakes', 2, 'цена ошибки выше цены секунды',
    /(договор|контракт|\bиск\b|исков|иску|суд(?:ебн|а|ом|иться)|закон|налог|бухгалтер|штраф|дозировк|лекарств|препарат|диагноз|симптом|лечени|здоровь|инвестиц|вклад|кредит|ипотек|страхов|продаж|продвиж|аренд|увольнен|сокращен)/iu),

  mark('ask', 2, 'человек попросил подумать',
    /(подумай|разберись\s+по(?:дробнее|внимательнее)|не\s+спеши|как\s+следует|внимательн(?:о|ее|ей)|без\s+спешки|тщательн(?:о|ее)|как\s+можно\s+(?:подробнее|точнее)|подробн(?:ый|о|ее)\s+разбор)/iu),

  /* «ошибк» и «падает» сами по себе — ещё не отладка: «я ошибся» и «дождь падает»
     не стоят дорогого прогона. Поэтому только в связке с местом, где это болит. */
  mark('debug', 2, 'разбор неполадки',
    /(почему\s+(?:не\s+)?(?:не\s+работает|падает|ломается|отвалива|краш)|не\s+работает|отлад(?:ка|ку|и)|дебаг|(?:ошибк|падает|падает\s+сборка|краш)\S*\s+(?:в\s+консол|в\s+лог|при\s+запуск|во\s+врем|на\s+прод|в\s+сборк|в\s+тест)|\b(?:exception|traceback|stack\s?trace|segmentation\s+fault|core\s+dumped|panic)\b)/iu),

  mark('arch', 2, 'проектное решение',
    /(архитектур|спроектир|спроект|микросервис|монолит|масштабиру|отказоустойчив|\bhighload\b|\bhigh\s?load\b)/iu),

  mark('compare', 1, 'сравнение с выбором',
    /(что\s+(?:лучше|выбрать|над[её]жнее)|сравни|чем\s+отлича|плюсы\s+и\s+минусы|за\s+и\s+против|альтернатив|аналог|\btrade-?offs?\b)/iu),

  mark('multi', 1, 'несколько связанных условий',
    /(с\s+уч[её]том|при\s+условии|несколько\s+(?:условий|факторов|ограничений|вопросов|задач)|ограничени|зависит\s+от|связан(?:о|ы)\s+между)/iu),

  mark('teach', 1, 'нужно объяснить, а не назвать',
    /(объясни|разъясни|почему\s+(?:так|именно)|как\s+работает|как\s+устроен|в\s+ч[её]м\s+(?:смысл|разница|суть)|за\s+сч[её]т\s+чего)/iu),
];

/** Длина вопроса — отдельная примета: свой порог, а не заимствованный у route.js. */
export const LONG_CHARS = 240;

/* ───────────────────── приметы, которые гасят глубину ─────────────────────
   Глубина на болтовне и творчестве — это усреднение голоса, тот же запрет, что
   у совета голов (engine/ensemble.js): там большинство не созывают на сценах и
   в стихах, здесь — не поднимают думающую модель. */
export const VETO = [
  {
    id: 'greeting',
    why: 'приветствие или короткая реплика',
    /* `^…$` — граница слова не нужна: совпадение и есть весь вопрос. */
    re: /^(привет|здравств|хай|hello|hi\b|ок\b|окей|хорошо|спасибо|благодарю|да\b|нет\b|понятно|ясно|ага)[\s!.,?…]*$/iu,
    test: (t) => /^(привет|здравств|хай|hello|hi|ок|окей|хорошо|спасибо|благодарю|да|нет|понятно|ясно|ага)[\s!.,?…]*$/iu.test(String(t || '').trim()),
  },
  {
    id: 'creative',
    why: 'творческая задача',
    re: /(придумай|сочини|поздравь|фанфик|поэм|стих|слоган|напиши\s+(?:стих|рассказ|шутку|анекдот|поздравлени|подпис|сценарий))/iu,
    test: (t) => wordHit(/(придумай|сочини|поздравь|фанфик|поэм|стих|слоган|напиши\s+(?:стих|рассказ|шутку|анекдот|поздравлени|подпис|сценарий))/iu, t),
  },
];

/**
 * Что слой возвращает. Всё — словами, чтобы решение можно было показать человеку
 * и завалить тестом.
 *
 * @typedef {{
 *   deep: boolean,
 *   why: string,
 *   score: number,
 *   hits: string[],
 *   veto: string,
 *   councilK: number,
 *   source: 'человек' | 'агент' | 'выключен',
 * }} DepthVerdict
 */

/** Конфиг из окружения (в Worker нет process.env — env приходит параметром). */
export function cfgOf(env) {
  const e = env || {};
  const mode = String(e.DEPTH || '').toLowerCase();
  const min = Number(e.DEPTH_MIN);
  return {
    /* DEPTH=off (или 0) — слой молчит, поведение прежнее: глубина только по явной просьбе. */
    on: mode !== 'off' && e.DEPTH !== '0',
    /* Порог можно поднять («глубже реже») и опустить («глубже чаще») без выката. */
    threshold: Number.isFinite(min) && min > 0 ? Math.min(6, Math.max(1, min)) : DEPTH_THRESHOLD,
    /* Сколько голов звать, когда задача дорогая. 0 — не трогать k ансамбля. */
    councilK: Math.max(0, Math.min(5, Number(e.DEPTH_COUNCIL_K) || 0)),
    /* DEPTH=always — глубина на всём, кроме запрещённого (нужно для пробы). */
    always: mode === 'always',
  };
}

/**
 * Решение о глубине.
 *
 * Вход — либо сам вопрос строкой (`judge('докажи…')`), либо объект с полями.
 * Строку слой обязан понимать: иначе вызов «просто с текстом» молча превращается
 * в пустой вопрос, и судья отвечает «не глубже» на доказательстве теоремы.
 *
 * @param {string|object} input
 * @param {string} [input.text]       вопрос человека
 * @param {string} [input.intent]     что уже решил классификатор (route.classifyTask)
 * @param {string[]} [input.images]   картинки: их решает совет зрячих, не глубина
 * @param {object} [input.env]        переменные развертывания
 * @param {boolean} [input.asked]     человек явно попросил глубже (внешний вызов, curl)
 * @returns {DepthVerdict}
 */
export function judge(input) {
  const i = typeof input === 'string' ? { text: input } : (input || {});
  const text = String(i.text == null ? '' : i.text);
  const cfg = cfgOf(i.env);
  const intent = String(i.intent || '');
  const base = { score: 0, hits: [], veto: '' };

  /* Явная просьба важнее правил: внешний вызов (curl, другой клиент) сам знает,
     чего он хочет. Судья в этом случае только подписывает причину словами. */
  if (i.asked === true) {
    return { ...base, deep: true, why: 'человек попросил глубже', councilK: cfg.councilK || 0, source: 'человек' };
  }
  if (!cfg.on) {
    return { ...base, deep: false, why: 'не глубже: судья выключен (DEPTH=off)', councilK: 0, source: 'выключен' };
  }

  const t = text.trim();
  if (!t) return { ...base, deep: false, why: 'не глубже: нечего разбирать', councilK: 0, source: 'агент' };

  /* Картинка — вотчина совета зрячих (engine/vcouncil.js): там голоса и арбитраж,
     а «думающая» модель на зрительном вопросе только сожжёт бюджет на размышления. */
  if (Array.isArray(i.images) && i.images.length) {
    return { ...base, deep: false, why: 'не глубже: задачу с картинкой решает совет зрячих', councilK: 0, source: 'агент' };
  }
  if (cfg.always) {
    return { ...base, deep: true, why: 'DEPTH=always', councilK: cfg.councilK || 0, source: 'агент' };
  }

  /* Отсекаем то, где глубина вредна: болтовня, приветствие, творчество. */
  for (const v of VETO) {
    if (v.test(t)) return { ...base, deep: false, veto: v.id, why: 'не глубже: ' + v.why, councilK: 0, source: 'агент' };
  }
  if (intent === 'creative') {
    return { ...base, deep: false, veto: 'creative', why: 'не глубже: творческая задача', councilK: 0, source: 'агент' };
  }

  /* Код, математика и зрение уже идут в свои головы (route.INTENT_HEADS) и в
     smart-очередь: поднимать их выше некуда, а жечь бюджет на размышления поверх
     своей головы — значит отвечать медленнее без выигрыша. */
  if (intent === 'code' || intent === 'math' || intent === 'vision') {
    return { ...base, deep: false, why: 'не глубже: у задачи свои головы и smart-очередь', councilK: 0, source: 'агент' };
  }

  let score = 0;
  const hits = [];
  const whys = [];
  for (const r of RULES) {
    if (r.test(t)) {
      score += r.weight;
      hits.push(r.id);
      whys.push(r.why);
    }
  }
  /* Длина — примета, а не приговор: длинный вопрос часто просто длинный. */
  if (t.length >= LONG_CHARS) {
    score += 1;
    hits.push('long');
    whys.push('длинный вопрос');
  }
  /* Вопросительных знаков больше одного — человек перечислил несколько вопросов.
     Очко добирается, только когда его не хватает ровно до порога: список вопросов
     не должен делать глубоким каждый запрос. */
  if (score === cfg.threshold - 1 && (t.match(/\?/g) || []).length >= 2) {
    score += 1;
    hits.push('many-questions');
    whys.push('несколько вопросов сразу');
  }
  score = Math.min(MAX_SCORE, score);

  const deep = score >= cfg.threshold;
  return {
    deep,
    why: deep
      ? whys.join(', ')
      : (whys.length
        ? 'не глубже: ' + whys.join(', ') + ' — очков ' + score + ' из ' + cfg.threshold
        : 'не глубже: примет глубины нет'),
    score,
    hits,
    veto: '',
    /* Дорогая задача — больше независимых проверок. 0 значит «не трогать k ансамбля». */
    councilK: deep && cfg.councilK > 0 ? cfg.councilK : 0,
    source: 'агент',
  };
}

/** Короткая подпись под ответом: её читает человек, поэтому она без кодов и очков. */
export function lineOf(verdict) {
  const v = verdict || {};
  if (!v.deep) return '';
  return v.why ? ' · глубже: ' + v.why : ' · глубже';
}
