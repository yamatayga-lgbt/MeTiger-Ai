/* ==================== 2) Реакция на прошлый ответ ==================== */

function words(s) {
  return String(s || '').toLowerCase().replace(/[^a-zа-яё0-9\s]/gi, ' ').split(/\s+/).filter((w) => w.length > 2);
}

function jaccard(a, b) {
  const A = new Set(a), B = new Set(b);
  let inter = 0;
  A.forEach((x) => { if (B.has(x)) inter++; });
  const uni = new Set([...A, ...B]).size;
  return uni ? inter / uni : 0;
}

export function readIntent(message, recentUser) {
  const text = String(message || '').trim();
  if (!text) return null;
  /* Первая сверху совпавшая цель — главная, но остальные тоже важны: «напиши
     эротическую сцену» — это и «сделать за него», и «сцена». Их перечисляем все,
     иначе человек получает готовый текст не того сорта. */
  const hits = GOALS.filter((g) => g.re.test(text));
  let goal = hits[0] || null;
  const also = hits.slice(1, 3);
  /* Вопрос без явной цели — это разбор, а не болтовня: «как тебя зовут» не talk. */
  if (!goal && /\?/.test(text)) goal = { key: 'answer', title: 'прямой ответ', want: 'Спрашивают — отвечай по существу первым же предложением, без «зависит от» и без встречного допроса.' };
  if (!goal) goal = { key: 'talk', title: 'поговорить и быть рядом', want: 'Короткая живая реплика; то, что он рассказал о себе, держи в разговоре.' };

  const shape = [];
  SHAPE.forEach((s) => { if (s.re.test(text)) shape.push(s); });

  /* Линия: ту же цель он тянет не первое сообщение? */
  let streak = 0;
  const others = Array.isArray(recentUser) ? recentUser.slice(-4) : [];
  others.forEach((t) => {
    const other = readIntent(t, []);
    if (other && other.key === goal.key) streak++;
  });

  return {
    key: goal.key, title: goal.title, want: goal.want,
    also: also.map((g) => ({ key: g.key, title: g.title, want: g.want })),
    shape: shape.map((s) => s.key), shapeTexts: shape.map((s) => s.text), streak,
  };
}

export function readReaction(message, prevReply, prevUser) {
  const text = String(message || '').trim();
  if (!text || !prevReply) return null;
  const signals = [];
  let kind = 'neutral';

  /* «нет, ...» в начале — отрицание ответа, а не отказ от темы. */
  if (MISS.test(text) || /^\s*нет[,!. ]/i.test(text)) { kind = 'miss'; signals.push('«не то»: ответил мимо запроса'); }
  if (ANGRY.test(text)) { kind = 'miss'; signals.push('раздражён прошлым ответом'); }
  if (/(короч|покороч|меньше текста|без воды|в две строки)/i.test(text)) { kind = kind === 'neutral' ? 'fix' : kind; signals.push('просит короче'); }
  if (/(подробнее|разверни|больше детал|конкретнее|до конца)/i.test(text)) { kind = kind === 'neutral' ? 'fix' : kind; signals.push('просит подробнее'); }
  if (/(не переспрашивай|сам реши|на твой вкус|делай как хочешь|реши сам)/i.test(text)) { kind = kind === 'neutral' ? 'fix' : kind; signals.push('раздражён переспрашиванием — решает сам'); }
  if (HIT.test(text)) { kind = 'hit'; signals.push('подтвердил: так и надо'); }

  /* Переспрос: задал по сути то же, что и в прошлый раз → прошлый ответ не сработал. */
  const a = words(text), b = words(String(prevUser || ''));
  if (a.length > 2 && b.length > 2 && jaccard(a, b) >= 0.5) {
    kind = 'miss';
    signals.push('повторил тот же вопрос: прошлый ответ не устроил, дай прямой и полный');
  }

  /* Что именно он подтвердил формой — закрепляем как проверенное. */
  const keep = [];
  SHAPE.forEach((s) => { if (s.key === 'shorter' || s.key === 'longer' || s.key === 'lists' || s.key === 'no_lists') { if (s.re.test(text)) keep.push(s.text); } });

  return { kind, signals, keep, asked: prevReply.slice(0, 220) };
}


/* ==================== 3) Что из этого следует ==================== */

function goalByKey(key) {
  const g = GOALS.find((x) => x.key === key);
  return g ? { key: g.key, title: g.title, want: g.want } : null;
}

export function resolveIntent(message, recentUser, reaction, prevGoalKey) {
  const intent = readIntent(message, recentUser);
  if (!intent) return null;
  const bare = intent.key === 'talk' || intent.key === 'answer';
  const rejected = reaction && (reaction.kind === 'miss' || reaction.kind === 'fix');
  const prev = goalByKey(prevGoalKey);
  if (!rejected || !bare || !prev || prev.key === intent.key) return intent;
  return {
    key: prev.key, title: prev.title, want: prev.want,
    also: intent.also, shape: intent.shape, shapeTexts: intent.shapeTexts,
    streak: (intent.streak || 0) + 1, inherited: true,
  };
}

export function directivesFrom(reaction, intent) {
  const out = [];
  if (intent && intent.shapeTexts) intent.shapeTexts.forEach((t, i) => out.push({ key: intent.shape[i], text: t }));
  if (!reaction) return out;
  if (reaction.kind === 'miss') {
    out.push({ key: 'answer_the_ask', text: 'сначала точно его запрос, потом уже своё' });
  }
  if (reaction.kind === 'hit') {
    (reaction.keep || []).forEach((t) => out.push({ key: 'confirmed:' + t, text: 'он подтвердил: ' + t }));
    out.push({ key: 'keep_course', text: 'так и вести: он подтвердил этот формат' });
  }
  if (reaction.signals.some((s) => /переспрашиван/.test(s))) out.push({ key: 'no_asking', text: 'не переспрашивать — решать самому и объявить выбор одной строкой' });
  if (reaction.signals.some((s) => /раздражён/.test(s))) out.push({ key: 'deliver', text: 'доводить до конца без оправданий и без «попробую»' });
  return out;
}


/** Блок в системный промпт: цель + проверенное про человека + что поправить сейчас. */

export function buildAttunePrompt(state) {
  const st = state || {};
  const lines = [];
  const intent = st.intent;
  const reaction = st.reaction;
  const prefs = Array.isArray(st.prefs) ? st.prefs : [];
  const turns = Number(st.turns) || 0;

  if (!intent && !prefs.length && !reaction) return '';

  lines.push('【Настройка на человека — характер, манера, цели】');
  lines.push('Ты не отвечаешь по шаблону: ты слышишь, ЧЕГО он хочет, и каждый следующий ответ делает это точнее.');

  if (intent) {
    lines.push(intent.inherited
      ? 'Задача та же, что и раньше: ' + intent.title + '. Новой он не ставил — он отверг прошлый вариант: переделай его, сохранив то, что было верным, и не разворачивай разговор в другую сторону. ' + intent.want
      : 'Сейчас он хочет: ' + intent.title + '. ' + intent.want);
    (intent.also || []).forEach((g) => lines.push('И в этом же сообщении: ' + g.title + '. ' + g.want));
    if (intent.shapeTexts && intent.shapeTexts.length) {
      lines.push('Форму он назвал сам: ' + intent.shapeTexts.join(', ') + '. Это закон, важнее любых твоих привычек.');
    }
    if (intent.streak >= 1) {
      lines.push('Он тянет это уже ' + (intent.streak + 1) + '-е сообщение: не начинай заново и не переспрашивай того, что уже сказал, — продолжай линию и углубляй.');
    }
  }

  if (prefs.length) {
    lines.push('Проверено в этом чате по ' + turns + ' ответам (держи всегда, он это подтвердил делом):');
    prefs.slice(-8).forEach((p) => {
      lines.push('• ' + p.text + (p.count > 1 ? ' — повторено ' + p.count + ' раза, точно' : ''));
    });
  }

  if (reaction && reaction.kind !== 'neutral') {
    if (reaction.kind === 'miss' || reaction.kind === 'fix') {
      lines.push('Прошлый ответ не попал (' + reaction.signals.join('; ') + '). '
        + 'Поправка: дай ровно то, о чём просил, полным и сразу; не извиняйся длинно — извинись одной строкой и сделай.');
    } else if (reaction.kind === 'hit') {
      lines.push('Прошлый ответ попал (' + reaction.signals.join('; ') + '). Закрепляй этот способ, не выдумывай новое на ровном месте.');
    }
  }

  lines.push('Рост по диалогу обязателен: учитывай, что он уже отверг, и не повторяй этого в новых формулировках; '
    + 'то, что он подтвердил, делай нормой для себя; о его фактах из памяти говори, когда они помогают, а не ради демонстрации.');

  return lines.join('\n');
}
