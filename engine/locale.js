/**
 * Русский слой качества (0.215) — против GigaChat и Алисы на их поле:
 * естественный русский, таблицы, локальные факты СНГ.
 *
 * Это не цензор и не «патриотический фильтр». Задача узкая: когда человек
 * пишет по-русски, ответ не должен выглядеть калькой с английского, путать
 * Беларусь с Россией и прятать сравнение в абзац, если его можно показать
 * таблицей. Поиск и авто-веб подхватывают те же маркеры страны, чтобы курс
 * Нацбанка не подменялся курсом ЦБ РФ.
 *
 * Слой чистый: никакой сети, никаких зависимостей. Его зовут chat.js
 * (подсказка стиля), search.js (добавка к поисковому промпту) и тесты.
 */

const CYR = /[а-яёА-ЯЁіІўЎ]/;

/* Беларусь — явным именем, городом, ведомством или валютой. */
const BY = /беларус|белорус|\bрб\b|\bby\b|гомел|гомель|мінск|минск|брест|витебск|віцебск|могил[её]в|магіл[её]ў|гродн|гродна|нбрб|нацбанк\s+рб|белстат|ерип|pravo\.by|nbrb|president\.gov\.by|\bbyn\b|бел\.?\s*рубл|лукашенк/i;

/* Россия — тем же правилом, плюс ЦБ РФ / Росстат / госуслуги РФ. */
const RU = /росси[яи]|российск|\bрф\b|москв|питер|санкт[-\s]?петербург|цб\s*рф|центробанк|росстат|consultant\.ru|cbr\.ru|\bруб(?:л|\b)|путин|\brub\b/i;

/** Сравнение, тариф, смета, расписание — ответ таблицей, не абзацем. */
const TABLE_ASK = /сравн[ия]|в\s+ч[её]м\s+разниц|versus|\bvs\b|тариф|расписан|смет[аыуе]|прайс|таблиц|\bxlsx\b|\bexcel\b|\bcsv\b|\btsv\b|что\s+лучше|что\s+выгоднее|сопостав/i;

/**
 * Страна вопроса: 'by' | 'ru' | ''. Пусто — не угадываем по IP и не
 * подставляем Минск вместо Москвы: лучше честно не знать, чем перепутать.
 */
export function regionOf(text) {
  const t = String(text || '');
  if (BY.test(t)) return 'by';
  if (RU.test(t)) return 'ru';
  return '';
}

export function wantsTable(text) {
  const t = String(text || '');
  if (TABLE_ASK.test(t)) return true;
  /* Вынутый xlsx/csv уже с табами — это и есть таблица, её надо сохранить. */
  if (/\t[^\n\t]+\t/.test(t)) return true;
  return false;
}

/**
 * Короткая добавка в system: числа, даты, таблица. Пусто, если вопрос
 * не по-русски и не про сравнение — английский код не засоряем.
 */
export function hint(text) {
  const t = String(text || '');
  const ru = CYR.test(t);
  const table = wantsTable(t);
  if (!ru && !table) return '';
  const bits = [];
  if (ru) {
    bits.push(
      'Пиши естественным русским, без кальки с английского и без канцелярита. '
      + 'Числа для человека — с пробелом тысяч и запятой («1 234,50»), даты — ДД.ММ.ГГГГ. '
      + 'Не путай Беларусь и Россию, Минск и Москву, BYN и RUB.',
    );
  }
  if (table) {
    bits.push(
      'Сравнение, тарифы, расписание, смету и данные из таблицы оформляй markdown-таблицей: '
      + 'строка заголовка, разделитель |---|---|, строки данных. '
      + 'Не описывай таблицу словами, если её можно показать.',
    );
  }
  return bits.join(' ');
}

/**
 * Добавка к поисковому промпту Gemini/Groq. Для латиницы — пусто.
 * Официальные домены названы явно: иначе выдача уходит в энциклопедию 2011 года.
 */
export function searchPrompt(q) {
  const t = String(q || '');
  if (!CYR.test(t)) return '';
  const r = regionOf(t);
  const head = 'Не путай Беларусь и Россию, BYN и RUB, Минск и Москву. '
    + 'Локальные факты (курс, тарифы, власть, законы, расписание) — с датой и названием ведомства.';
  if (r === 'by') {
    return head + ' Официальные источники Беларуси: nbrb.by, belstat.gov.by, pravo.by, '
      + 'president.gov.by, minfin.gov.by, mvd.gov.by. Курс — Нацбанк РБ, не ЦБ РФ.';
  }
  if (r === 'ru') {
    return head + ' Официальные источники России: cbr.ru, rosstat.gov.ru, consultant.ru, '
      + 'government.ru, gosuslugi.ru. Курс — ЦБ РФ, не Нацбанк РБ.';
  }
  return head + ' Если страна не названа, не подменяй одну другой: для курса без страны '
    + 'назови НБРБ (BYN) отдельно от ЦБ РФ (RUB).';
}

