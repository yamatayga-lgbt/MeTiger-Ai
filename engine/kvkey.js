/**
 * Ключи для KV — одна функция на всю систему. Правила у Cloudflare на удивление
 * мягкие (до 512 байт, любые печатные непробельные символы), но свои три причины
 * здесь сильнее, чем «разрешено/запрещено»:
 *
 *   · длина: ключ чата приходит от клиента, и обрезка по 512 байтам на глазах
 *     склеивает два разных запроса в одно хранилище;
 *   · пробелы и переносы в ключах KV — то, что потом невозможно найти в списке,
 *     а Telegram-имена чатов и ip v6 приходят именно такие;
 *   · в ключ попадает ip клиента. Хранить его открытым незачем: проекту довольно
 *     знать, что это тот же собеседник, а не кто он.
 *
 * Ключи, начинающиеся с точки, часть интерфейсов (в том числе REST-обход к KV)
 * режет — их тоже приводим.
 */

/** FNV-1a, 32 бита, стабильный между изоляторами и перезапусками (в отличие от hash-строк рантайма). */
export function fnv1a(str) {
  let h = 0x811c9dc5;
  const s = String(str || '');
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 0x01000193) >>> 0;
  }
  return h.toString(36);
}

/**
 * Безопасный ключ: `<prefix>:<slug><хэш, если резали>`. Слаг сохраняет читаемость
 * (`chat:tg_123` хочется видеть в списке), хэш — то, что из-за вырезанных символов
 * два разных клиента не склеились в один ключ.
 */
export function kvKey(prefix, raw, maxLen) {
  const full = String(raw == null ? '' : raw);
  const kept = maxLen || 48;
  /* Точку в слаг не пускаем намеренно: KV её терпит, но любой файловый адаптер
     (такой есть в scripts/api-dev.js) превращает `..` в приглашение пройтись
     выше каталога. Дешевле вырезать, чем объяснять это потом. */
  let slug = full.replace(/[^A-Za-z0-9_-]+/g, '_').replace(/^[._-]+|[._-]+$/g, '').slice(0, kept);
  const digest = fnv1a(full);
  // пустой слаг бывает всегда, когда вход — не ASCII (ip v6, русское имя чата);
  // хэш тогда и есть весь ключ
  const body = slug ? (slug === full ? slug : slug + '-' + digest) : digest;
  return String(prefix || 'k') + ':' + body;
}
