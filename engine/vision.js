/**
 * Базовая рамка для любой картинки. Она специально разделяет наблюдение,
 * вывод и неуверенность: модель реже прячется за общий отказ и реже сочиняет.
 */
export function visionSystemBlock(text) {
  const task = classifyVisionTask(text);
  return [
    'Работа с изображением: сначала назови прямо наблюдаемое, затем вывод, затем то, что по кадру установить нельзя. Отвечай именно на вопрос человека обычным языком, без морализаторства. Если требуемая глубина недоступна, дай максимально полезный фактологический разбор доступной части: состав кадра, предметы, текст, фон, свет, действие в общих словах и качество. Реальные риски по делу — коротко после сути, а не вместо неё. Не дорисовывай невидимое и не выдавай догадку за наблюдение.',
    MODE_LINES[task.mode] || MODE_LINES.general,
  ].join('\n');
}

/** Короткая приписка прямо за репликой человека: слабые головы системную
 * рамку иногда теряют, а локальную задачу в самом запросе — почти никогда. */
export function visionInlineNote(text) {
  const task = classifyVisionTask(text);
  if (!task || task.mode === 'general') return '';
  return '[режим анализа вложения: ' + task.mode + '; фокус — ' + task.focusLabel
    + '; сначала наблюдаемое, затем вывод и неуверенность]';
}

function originalQuestion(text) {
  const t = String(text || '').trim();
  return t || 'Что видно на изображении?';
}

