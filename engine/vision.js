/**
 * Анализ изображений без «голого отказа» (0.210).
 *
 * Один и тот же кадр провайдеры встречают по-разному: одной модели хватает
 * обычного вопроса, вторая отвечает только на инвентаризацию видимого,
 * третья — только на одну конкретную деталь, четвёртая — на визуальные
 * якоря (текст, предметы, фон, свет, композицию). Этот модуль не угадывает
 * содержимое за модель и не обходит жёсткие границы: он раскладывает ОДИН
 * вопрос человека по ступеням детализации, чтобы честный фактологический
 * ответ не сгорал из-за одного неудачно сформулированного запроса.
 *
 * Runtime-независимость: без process.env и fs.
 */

