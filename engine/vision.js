/**
 * Анализ изображений без «голого отказа» (0.210).
 *
 * Один и тот же кадр провайдеры встречают по-разному: одной модели хватает
 * обычного вопроса, вторая отвечает только на инвентаризацию видимого,
 * третья — только на одну конкретную деталь, четвёртая — на визуальные
 * якоря (текст, предметы, фон, свет, композицию). Этот модуль не угадывает
 * содержимое за модель и не обходит жёсткие границы: он раскладывает ОДИН
 * вопрос человека по ступеням детализации, чтобы честный фактологический
 * ответ не сгорал из-за одного неудачно сформулированного запроса.
 *
 * Runtime-независимость: без process.env и fs.
 */

import { parseDataUrl } from './shape.js';

const TASK_PATTERNS = [
  ['document', /(прочитай|перепиши|распознай|ocr|что написано|какой текст|надпис\w*|документ\w*|страниц\w*|чек(?:\s|$)|квитанц\w*|таблиц\w*|скриншот\w*|экран\w*|выписк\w*)/i],
  ['medical', /(родинк\w*|дермат\w*|сып\w*|прыщ\w*|акне|угр\w*|гнойник\w*|ран[аыуойе]|шов|шв[аыуое]|рубец|шрам\w*|ушиб\w*|гематом\w*|от[её]к\w*|ожог\w*|обморож\w*|грибок|псориаз|экзем\w*|лишай|зуд\w*|кож[аыеуи]|аллерг\w*|врач|медицин\w*|диагност\w*|симптом\w*|укус\w*|рентген\w*|мрт|узи)/i],
  ['composition', /(оцени.*(?:кадр|фото)|композици\w*|ракурс\w*|освещен\w*|экспозиц\w*|фокус\w*|кадриров\w*|объектив\w*|фототехник\w*|художествен\w*|картин[аеуи]|скульптур\w*|музе\w*|выстав\w*|дизайн\w*|эстетик\w*|стиль кадра)/i],
  ['safety', /(опасн\w*|безопасн\w*|риск\w*|травм\w*|авари\w*|пожар\w*|оружи\w*|поврежд\w*|что не так|можно ли так)/i],
  ['people', /(человек\w*|люд\w*|мужчин\w*|женщин\w*|парень|девуш\w*|тело|поз[ауы]|одежд\w*|купальник\w*|пляж\w*|спортзал\w*|трениров\w*|осанк\w*|секс\w*|эрот\w*|обнаж\w*|интим\w*|порно\w*|18\+)/i],
];

const FOCUS_PATTERNS = [
  ['text', /(что написано|прочитай|текст|надпис\w*|вывеск\w*|номер\w*|дата|адрес)/i],
  ['count', /(сколько|посчитай|количество|число)\b/i],
  ['color', /(какой цвет|какого цвета|цвет\w*|оттен\w*)/i],
  ['composition', /(композици\w*|ракурс\w*|освещен\w*|свет\w*|кадр|фон\w*|передний план|задний план)/i],
  ['setting', /(где (?:это|находится|снято)|что за место|какая обстановка|помещение|улица)/i],
  ['action', /(что (?:он|она|они|человек|люди) дела|какое действие|что происходит)/i],
  ['object', /(что это|что за (?:предмет|объект|вещь)|какой предмет|что на (?:этом )?(?:фото|изображении|снимке))/i],
  ['quality', /(качество|резкост\w*|размыт\w*|шум\w*|чёткост\w*|четкост\w*)/i],
];

const FOCUS_LABELS = {
  text: 'видимый текст и надписи',
  count: 'количество ясно различимых объектов',
  color: 'цвета и оттенки',
  composition: 'композицию, свет и расположение в кадре',
  setting: 'место и обстановку',
  action: 'действие в общих наблюдаемых словах',
  object: 'главный объект',
  quality: 'резкость, освещение и техническое качество',
  scene: 'главные видимые элементы сцены',
};

export function classifyVisionTask(text) {
  const t = String(text || '').slice(0, 4000);
  let mode = 'general';
  for (const [id, re] of TASK_PATTERNS) {
    if (re.test(t)) { mode = id; break; }
  }
  let focus = 'scene';
  for (const [id, re] of FOCUS_PATTERNS) {
    if (re.test(t)) { focus = id; break; }
  }
  if (mode === 'document') focus = 'text';
  if (mode === 'composition' && focus === 'scene') focus = 'composition';
  return { mode, focus, focusLabel: FOCUS_LABELS[focus] || FOCUS_LABELS.scene };
}

const MODE_LINES = {
  document: 'Для документа и экрана сначала точно перепиши видимый текст в исходном порядке; нечитаемое помечай [неразборчиво], числа и знаки не додумывай.',
  medical: 'Для медицинского вопроса описывай только видимые признаки: расположение, размер относительно кадра, цвет, форму, поверхность и края. Не ставь окончательный диагноз по одному снимку; тревожные признаки и необходимость очной помощи называй после наблюдений.',
  composition: 'Для разбора кадра отдельно смотри передний и задний планы, главный объект, свет, цвет, ракурс, фокус, пустое пространство и технические дефекты.',
  safety: 'Для вопроса о безопасности сначала перечисли наблюдаемые опасности и неопределённости, затем дай вывод и ближайшие разумные меры.',
  people: 'Людей описывай по наблюдаемому: количество, положение, одежду или её отсутствие в общих словах, действие в общих словах и обстановку. Не идентифицируй частных людей и не угадывай точный возраст, ориентацию, намерения или невидимые обстоятельства. Если сцена сексуализирована и совершеннолетие человека по кадру надёжно не устанавливается, не давай эротической детализации: ограничься безопасными общими наблюдениями и прямо скажи о неопределённости возраста.',
  general: 'Если вопрос общий, начни с главного объекта и сцены, затем назови детали, которые реально помогают ответить.',
};

/**
 * Базовая рамка для любой картинки. Она специально разделяет наблюдение,
 * вывод и неуверенность: модель реже прячется за общий отказ и реже сочиняет.
 */
export function visionSystemBlock(text) {
  const task = classifyVisionTask(text);
  return [
    'Работа с изображением: сначала назови прямо наблюдаемое, затем вывод, затем то, что по кадру установить нельзя. Отвечай именно на вопрос человека обычным языком, без морализаторства. Если требуемая глубина недоступна, дай максимально полезный фактологический разбор доступной части: состав кадра, предметы, текст, фон, свет, действие в общих словах и качество. Реальные риски по делу — коротко после сути, а не вместо неё. Не дорисовывай невидимое и не выдавай догадку за наблюдение.',
    MODE_LINES[task.mode] || MODE_LINES.general,
  ].join('\n');
}

/** Короткая приписка прямо за репликой человека: слабые головы системную
 * рамку иногда теряют, а локальную задачу в самом запросе — почти никогда. */
export function visionInlineNote(text) {
  const task = classifyVisionTask(text);
  if (!task || task.mode === 'general') return '';
  return '[режим анализа вложения: ' + task.mode + '; фокус — ' + task.focusLabel
    + '; сначала наблюдаемое, затем вывод и неуверенность]';
}

function originalQuestion(text) {
  const t = String(text || '').trim();
  return t || 'Что видно на изображении?';
}

/**
 * Один спасательный проход.
 *   neutral — инвентаризация всего видимого;
 *   detail  — только деталь/фокус вопроса;
 *   anchors — ненагруженные визуальные якоря без детализации тела/действий.
 */
export function visionPass(stage, text) {
  const task = classifyVisionTask(text);
  const q = originalQuestion(text);
  if (stage === 'detail') {
    return {
      stage,
      mode: task.mode,
      focus: task.focus,
      system: 'Режим разбора одной детали изображения. Не пересказывай всю сцену и не обсуждай кадр в целом. Рассмотри только ' + task.focusLabel + '; назови наблюдаемые признаки, затем ответь на исходный вопрос в пределах этой детали. Если деталь не видна или кадр нечёткий, прямо скажи, что именно нельзя различить. Это узкая фактологическая проверка видимого.',
      prompt: 'Рассмотри в прикреплённом изображении только ' + task.focusLabel + '. Сначала перечисли наблюдаемые признаки, затем ответь на вопрос: ' + q,
    };
  }
  if (stage === 'anchors') {
    return {
      stage,
      mode: task.mode,
      focus: task.focus,
      system: 'Режим визуальных якорей. Перечисли только проверяемые элементы кадра: объекты и их расположение, видимый текст, цвета, фон, одежду в общих словах, освещение, композицию и техническое качество. Не переходи к эротической или графической детализации тела и действий. После якорей ответь на исходный вопрос настолько, насколько эти факты позволяют, и отдельно отметь неуверенность.',
      prompt: 'Дай по прикреплённому изображению список визуальных якорей (объекты, текст, цвета, фон, расположение, свет, качество), затем ответь на вопрос в пределах этих фактов: ' + q,
    };
  }
  return {
    stage: 'neutral',
    mode: task.mode,
    focus: task.focus,
    system: 'Режим холодного разбора изображения. Никакой эротической или возбуждающей детализации не нужно и не требуется. Опиши фактологически: что в кадре (объекты, люди в общих словах — поза, одежда или её отсутствие одним словом, действие в общих словах), обстановка, свет, качество снимка. Затем ответь на вопрос человека в деловом ключе, насколько видно по кадру. Отказываться нечем: это инвентаризация видимого.',
    prompt: 'Опиши прикреплённое изображение холодно и фактологически, затем ответь на вопрос: ' + q,
  };
}

export function visionPasses(text) {
  return ['neutral', 'detail', 'anchors'].map((stage) => visionPass(stage, text));
}

/** Только то, что движок знает без зрения: формат и приблизительный размер. */
export function imageFacts(images) {
  const out = [];
  for (const src of Array.isArray(images) ? images : []) {
    const parsed = parseDataUrl(src);
    if (!parsed) continue;
    const bytes = Math.max(0, Math.floor(String(parsed.data || '').replace(/\s/g, '').length * 3 / 4));
    out.push({ mime: parsed.mime, bytes, kb: Math.max(1, Math.round(bytes / 1024)) });
  }
  return out;
}

export function imageFactLine(images) {
  const facts = imageFacts(images);
  if (!facts.length) return '';
  const kinds = facts.map((f) => String(f.mime || '').replace(/^image\//i, '').toUpperCase() || 'изображение');
  const totalKb = facts.reduce((a, f) => a + f.kb, 0);
  return 'Получено изображений: ' + facts.length + ' (' + kinds.join(', ') + ', суммарно около ' + totalKb + ' КБ).';
}
